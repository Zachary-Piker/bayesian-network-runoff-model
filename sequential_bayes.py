# label, physical units, log10 scale
PARAM_INFO = {
    "c_ms": ("c", "m/s", False), "log10_D": ("D", "m²/s", True),
    "log10_k_hill": ("k_hill", "h", True), "fc": ("f_c", "in/h", False),
    "a_imp": ("a", "-", False), "beta": ("β", "-", False), "log10_k_gw": ("k_gw", "h", True),
    "ia_mean": ("Ia mean", "in", False), "ia_slope": ("Ia slope", "in per sd of log10 Q0", False),
}
IA_BOUNDS = {"ia_mean": (0.0, 6.0), "ia_slope": (-2.0, 2.0)}


def default_prior(names: Sequence[str]) -> dict:
    """Weakly informative normal starting priors (mean, sd) in parameter-space units.
    D, k_hill and k_gw are estimated in log10 (so they have log-normal priors).
        c        N(1.0, 0.6) m/s
        D        10^N(2.5, 0.7) m²/s      ±2 sd: 13-8000 m²/s
        k_hill   10^N(0.3, 0.5) h         ±2 sd: 0.2-20 h
        fc       N(0.10, 0.10) in/h
        a        N(0.03, 0.03)
        beta     N(0.15, 0.15)
        k_gw     10^N(log10 72, 0.5) h    ±2 sd: 7-720 h
        ia_mean  N(0.6, 0.5) in
        ia_slope N(0.0, 0.3) in           per sd of log10 Q0; sign not constrained"""
    base = {"c_ms": (1.0, 0.6), "log10_D": (2.5, 0.7), "log10_k_hill": (0.3, 0.5),
            "fc": (0.10, 0.10), "a_imp": (0.03, 0.03), "beta": (0.15, 0.15),
            "log10_k_gw": (float(np.log10(72.0)), 0.5),
            "ia_mean": (0.6, 0.5), "ia_slope": (0.0, 0.3)}
    return {k: base[k] for k in names}


def to_physical(name: str, v):
    """Estimation units to physical units (10**v for log10 parameters)."""
    return 10 ** np.asarray(v) if PARAM_INFO[name][2] else np.asarray(v)


def param_names(a_imp, use_gw):
    """Parameter names and bounds in parameter-space (estimation) units, with Ia regression last."""
    names, lo, hi, _, _ = d.param_space(a_imp, use_gw)
    names = list(names) + ["ia_mean", "ia_slope"]
    lo = np.r_[lo, IA_BOUNDS["ia_mean"][0], IA_BOUNDS["ia_slope"][0]]
    hi = np.r_[hi, IA_BOUNDS["ia_mean"][1], IA_BOUNDS["ia_slope"][1]]
    return names, lo, hi


# ----------------------------------------------------------------------------- model evaluation

def simulate(ev, p: d.DistParams, ia: float, router, dt: float, kb_days):
    """Simulated event flow, observed event flow and pre-storm recession for given Ia."""
    n = len(ev.Q_obs)
    pe = d.cell_excess(ev.rain_cells, p, ia, dt)
    quick = router.route(pe, p, length=n)
    if kb_days is None:
        return quick, ev.Q_direct_obs, ev.baseflow
    ret = d.gw_return_flow(d.infiltration(ev.rain_cells, pe, router.cells.area_mi2.values), p, dt, n)
    rec = d.recession(ev.q0(kb_days), n, dt, kb_days)
    return quick + ret, ev.Q_obs - rec, rec


def storm_rain_max(ev) -> float:
    """Maximum storm-total rainfall on any cell (inside); upper bound for Ia."""
    return float(np.nansum(ev.rain_cells, axis=0).max())


def _noise(r):
    """Returns (s^2, sigma^2, rho): residual variance inflated for lag-1 autocorrelation."""
    sigma2 = float(np.mean(r ** 2))
    rho = float(np.corrcoef(r[:-1], r[1:])[0, 1]) if len(r) > 3 and np.std(r) > 0 else 0.0
    rho = float(np.clip(np.nan_to_num(rho), 0.0, 0.98))
    return max(sigma2, 1e-8) * (1 + rho) / (1 - rho), sigma2, rho


def _jacobian(f, x, lo, hi, f0, rel=5e-3):
    """Forward-difference Jacobian; backward step at an upper bound."""
    J = np.empty((len(f0), len(x)))
    for j in range(len(x)):
        h = rel * max(0.05, abs(x[j]))
        h = -h if x[j] + h > hi[j] else h
        xj = x.copy(); xj[j] += h
        J[:, j] = (f(xj) - f0) / h
    return J

