def plot_storm_grid(res: SequentialResult, storms=None, ncols: int = 4, show_after: bool = True,
                    hours: Optional[float] = None, title: Optional[str] = None):
    """Big grid of storm forecasts with one panel per storm (k: 0-based, date order).
    Event flow (observed minus pre-storm recession): observed (black), forecasted
    with a 90 % interval (orange) and, if show_after, posterior fit (green).
    Inverted bars: basin-mean rainfall (light) and effective rainfall of the
    forecast (dark). Panel title: rainfall, runoff and forecasted NSE."""
    import matplotlib.pyplot as plt
    ks = list(range(len(res.events))) if storms is None else list(storms)
    if not ks:
        raise ValueError("no storms to plot")
    ncols = min(ncols, len(ks))
    nrows = int(np.ceil(len(ks) / ncols))
    fig, axs = plt.subplots(nrows, ncols, figsize=(4.9 * ncols, 3.25 * nrows), squeeze=False)
    A = res.cells.area_mi2.values
    w_h = res.dt
    for i, k in enumerate(ks):
        ax = axs.flat[i]
        ev, fc = res.events[k], res.forecasts[k]
        t = (np.arange(len(ev.Q_obs))) * res.dt
        rec = fc["recession"]
        obs = ev.Q_obs - rec
        q_f = fc["Q_forecast"] - rec
        if fc.get("band") is not None:
            ax.fill_between(t, np.maximum(fc["band"][0] - rec, 0), fc["band"][1] - rec, color="#fdd0a2",
                            alpha=0.8, lw=0, label="forecast 90 % interval")
        if show_after and fc.get("Q_after") is not None:
            ax.plot(t, fc["Q_after"] - rec, color="#1b7837", lw=1.2, ls="--", label="posterior fit")
        ax.plot(t, obs, "k", lw=1.2, label="observed event flow")
        ax.plot(t, q_f, color="#d95f02", lw=1.8, label="forecast")
        # effective rainfall of the forecast: prior mean parameters, Ia from the regression
        p_k = res.params(k)
        rain = ev.rain_cells @ A / A.sum() / res.dt
        pe = d.cell_excess(ev.rain_cells, p_k, fc["Ia_forecast"], res.dt) @ A / A.sum() / res.dt
        ax2 = ax.twinx()
        ax2.bar(t, rain, width=w_h, align="edge", color="#9ecae1", lw=0)
        ax2.bar(t, pe, width=w_h, align="edge", color="#2171b5", lw=0)
        ax2.set_ylim(max(rain.max(), 1e-3) * 3.2, 0)
        ax2.tick_params(labelsize=7.5)
        ax.set_zorder(ax2.get_zorder() + 1); ax.patch.set_visible(False)
        # x range: rainfall onset to the end of the event-flow recession
        ipk = int(np.argmax(obs))
        tail = np.nonzero(obs[ipk:] < 0.05 * max(obs[ipk], 1e-6))[0]
        iend = min(len(t) - 1, ipk + (tail[0] if len(tail) else len(t)) + int(6 / res.dt))
        wet = np.nonzero(rain > 0)[0]
        x0 = max(0.0, (wet[0] * res.dt - 4.0) if len(wet) else 0.0)
        x1 = min(max(t[iend], x0 + 24.0), x0 + max(48.0, 4 * (t[ipk] - x0)))   # limit long recessions
        ax.set_xlim(x0, x0 + hours if hours else x1)
        top = max(obs.max(), q_f.max(), (fc["band"][1] - rec).max() if fc.get("band") is not None else 0)
        ax.set_ylim(0, top * 1.6)
        ax.tick_params(labelsize=7.5)
        nse = m.nse(obs, q_f)
        ax.set_title(f"Storm {k + 1}, {ev.time[0]:%Y-%m-%d}: P {ev.rain_in:.2f} in, "
                     f"Q {ev.runoff_in:.2f} in, NSE {nse:.2f}", fontsize=8.5)
        if i % ncols == 0:
            ax.set_ylabel("Event flow (cfs)", fontsize=9)
        if i % ncols == ncols - 1 or i == len(ks) - 1:
            ax2.set_ylabel("Rainfall (in/h)", fontsize=9)
        if i >= len(ks) - ncols:
            ax.set_xlabel("Hours from window start", fontsize=9)
        if i == 0:
            ax.legend(fontsize=7, loc="center right", framealpha=0.95)
    for ax in axs.flat[len(ks):]:
        ax.set_visible(False)
    fig.suptitle(title or "Forecast (orange, 90 % interval), observed (black) and posterior fit (green dashed); "
                          "rainfall: total (light), effective (dark)",
                 fontsize=11.5)
    fig.tight_layout(rect=(0, 0, 1, 1 - 0.45 / fig.get_size_inches()[1]))   # space for suptitle
    return fig


def plot_ia_relation(res: SequentialResult, ax=None):
    """Posterior Ia of each storm (at its update) against the pre-storm flow, including
    the final regression and its ±1.645 tau interval."""
    import matplotlib.pyplot as plt
    if ax is None:
        _, ax = plt.subplots(figsize=(7.5, 4.6))
    h = res.history
    lq = h.z_logQ0 * res.zq[1] + res.zq[0]
    ax.errorbar(lq, h.Ia_posterior_in, yerr=1.645 * h.Ia_posterior_sd, fmt="o", color="#2b8cbe",
                ecolor="#9ecae1", mec="k", mew=0.4, ms=6, capsize=0, label="storm Ia, posterior (90 % interval)")
    q_ = np.linspace(lq.min(), lq.max(), 50)
    mu = res.means[-1]
    line = mu[-2] + mu[-1] * (q_ - res.zq[0]) / res.zq[1]
    ax.fill_between(q_, np.maximum(line - 1.645 * res.tau_ia, 0), line + 1.645 * res.tau_ia,
                    color="0.88", label="regression ± 1.645 τ")
    ax.plot(q_, line, "k", lw=2, label="regression (posterior mean)")
    ax.set(xlabel="log10 pre-storm flow Q0 (cfs)", ylabel="Initial abstraction Ia (in)",
           title="Initial abstraction and antecedent flow")
    ax.set_ylim(bottom=0)
    ax.legend(fontsize=8, framealpha=0.95)
    ax.grid(alpha=0.3)
    return ax
