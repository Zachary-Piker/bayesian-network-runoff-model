"""
FUNCTIONS GENERATED BY CLAUDE OPUS 5.5


=====================================================
Sequential Bayesian calibration of the network model.
=====================================================

All parameters start with normal priors. Storms are then processed by date order, and each
update applies the likelihood · priors:

    p(theta | y_1..k)  ∝  p(y_k | theta) · p(theta | y_1..k-1)

theta = model parameters        c, log10 D, log10 k_hill, fc, (a), (beta, log10 k_gw)
      + Ia regression           ia_mean, ia_slope

Storm k has its own Ia_k, which is distributed about a regression on the standardized pre-storm flow:

    Ia_k ~ N( ia_mean + ia_slope · z_k ,  tau² )      z_k = standardized log10 Q0_k

ia_mean and ia_slope are estimated with the other parameters; tau (TAU_IA) is
fixed, and forecasts use the regression model. In the updating process, Ia_k is estimated jointly
with theta and then marginalized.

Each update uses a Laplace (normal) approximation of the posterior distribution:

    joint prior of (theta, Ia_k)     N(m_aug, P_aug)    (Ia_k = H theta + noise)
    posterior mode (MAP)             minimize  Σ r_j² / s²  +  (φ - m_aug)' P_aug⁻¹ (φ - m_aug)
    posterior covariance             P_new = ( J'J / s² + P_aug⁻¹ )⁻¹,   J = ∂r/∂φ at the MAP
    theta block                      prior for the next storm (Ia_k marginalized)

r_j = (simulated - observed event flow) / observed peak, at each modeling time step.
s² = σ²(1 + ρ)/(1 - ρ) is the residual variance inflated to accunt for the lag-1
autocorrelation ρ. σ and ρ are estimated from each storm's residuals
and carry no prior information.

The MAP is computed with scipy.optimize.least_squares (bounded trust-region
reflective). The bounds enforce physical constraints (c > 0.1 m/s, fc ≥ 0,
0 ≤ Ia ≤ storm rainfall, ...) and truncate the priors.

drift > 0 adds the fraction of the prior covariance before each update
(covariance inflation), which allows for a slower parameter change over time.

Main functions
    default_prior, sequential_update -> SequentialResult
    SequentialResult.update_storm    -> forecasting and parameter update for one storm
    SequentialResult.predict         -> forecast without update
    SequentialResult.to_fit          -> distributed_iuh.DistFit at the posterior mean
    run_saved                        -> sequential_update using on-disk cache
    posterior_table, plot_parameter_paths, plot_forecast_skill, plot_storm_forecast,
    plot_forecast_with_map, plot_storm_grid, plot_ia_relation, plot_posterior_correlation
"""

