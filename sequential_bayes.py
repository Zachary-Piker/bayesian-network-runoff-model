@dataclass
class SequentialResult:
    names: list
    lo: np.ndarray
    hi: np.ndarray
    prior_mean: np.ndarray
    prior_cov: np.ndarray
    means: list                  # prior mean and then posterior mean after each storm
    covs: list
    history: pd.DataFrame        # one row per storm in order by date
    forecasts: list              # per storm (date order): forecast, interval, posterior fit
    router: d.Router
    events: list                 # in date order
    order: np.ndarray            # events[j] = input_events[order[j]]
    input_events: list
    cells: pd.DataFrame
    dt: float
    gauge_area_mi2: float
    kb_days: Optional[float]
    a_imp: Optional[float]
    tau_ia: float
    zq: tuple                    # (mean, sd) of log10 Q0 for standardiing z
    d_imp: float = 0.05
    batch_x: Optional[np.ndarray] = None
    settings: dict = field(default_factory=dict)
    state: dict = field(default_factory=dict)

    @property
    def use_gw(self):
        return self.kb_days is not None

    @property
    def n_model(self):
        return len(self.names) - 2

    def params(self, k: int = -1) -> d.DistParams:
        """Model parameters at the posterior mean after storm k (default: final)."""
        return d._unpack(self.means[k][:self.n_model], self.a_imp, self.d_imp, self.use_gw)

    def sd(self, k: int = -1) -> np.ndarray:
        """Posterior standard deviations after storm k (estimation units)."""
        return np.sqrt(np.diag(self.covs[k]))

    def z(self, ev) -> float:
        """Standardised log10 pre-storm flow of storm event ev."""
        return (np.log10(max(ev.q0(self.kb_days) if self.kb_days else ev.Q0, 1e-3)) - self.zq[0]) / self.zq[1]

    def ia_prior(self, ev, k: int = -1):
        """Prior mean and sd of Ia for storm ev, from the posterior after storm k."""
        mu, P = self.means[k], self.covs[k]
        H = np.zeros(len(mu)); H[-2], H[-1] = 1.0, self.z(ev)
        return float(H @ mu), float(np.sqrt(H @ P @ H + self.tau_ia ** 2))

    def predict(self, ev, n_samples: int = 30, k: int = -1, seed: int = 0,
                model_error_sd: Optional[float] = None) -> dict:
        """Forecasted storm ev from the posterior after storm k, without an update.
        Central forecast: posterior mean parameters and Ia from the regression model.
        90 % interval: parameter and Ia samples combined with the median
        residual sd of the processed storms so far."""
        rng = np.random.default_rng(seed)
        mu, P = self.means[k], self.covs[k]
        return _forecast(ev, mu, P, self, rng, n_samples,
                         model_error_sd if model_error_sd is not None else self.typical_error())

    def update_storm(self, ev, verbose: bool = True) -> dict:
        """Forecasted storm ev from the current prior used for forecasting, then used for update. The
        posterior becomes the prior for the next storm according to the updating procedure. 
        Returns the forecast dictionary, including the posterior fit and both 90 % intervals. Storms must
        be added in date order."""
        return _update_storm(self, ev, verbose)

    learn_storm = update_storm          # former name, kept for older notebook versions

    def typical_error(self) -> float:
        """Median residual sd (peak-normalized) of the processed storms."""
        sd = self.history.resid_sd.dropna()
        return float(sd.median()) if len(sd) else 0.05

    def ia_posterior(self, ev, p: Optional[d.DistParams] = None, s2: Optional[float] = None):
        """Conditional posterior mode of Ia for storm ev, with parameters fixed at
        p (default: final posterior mean) and prior N(ia_mean + ia_slope z, tau²).
        Returns (Ia, status)."""
        p = p or self.params()
        mu = self.means[-1]
        prior_m = float(mu[-2] + mu[-1] * self.z(ev))
        s2 = s2 if s2 is not None else self.typical_error() ** 2
        ptot = storm_rain_max(ev)

        def obj(ia):
            sim, target, base = simulate(ev, p, ia, self.router, self.dt, self.kb_days)
            r = (sim - target) / max(target.max(), 1e-6)
            return np.sum(r ** 2) / s2 + (ia - prior_m) ** 2 / self.tau_ia ** 2
        grid = np.linspace(0.0, ptot, 25)                 # grid search first: objective can be flat
        j = int(np.argmin([obj(g) for g in grid]))
        ia = optimize.minimize_scalar(obj, bounds=(grid[max(j - 1, 0)], grid[min(j + 1, 24)]),
                                      method="bounded", options={"xatol": 1e-4}).x
        st = "ok" if 1e-3 < ia < ptot - 1e-3 else ("Ia_at_zero" if ia <= 1e-3 else "Ia_at_storm_rain")
        return float(ia), st

    def to_fit(self) -> d.DistFit:
        """distributed_iuh.DistFit at the final posterior mean. Each storm's Ia is
        its conditional posterior mode (ia_posterior)."""
        p = self.params()
        mu = self.means[-1]
        s2 = dict(zip(self.order, self.history.s2.values))
        rows = []
        for i, ev in enumerate(self.input_events):
            prior_m = float(mu[-2] + mu[-1] * self.z(ev))
            ia, st = self.ia_posterior(ev, p, s2.get(i))
            sim, target, base = simulate(ev, p, ia, self.router, self.dt, self.kb_days)
            loc = d.rain_location(ev, self.cells)
            tm = d.timing_metrics(target, sim, self.dt)
            rows.append({"start": ev.time[0], "rain_in": ev.rain_in, "runoff_in": ev.runoff_in,
                         "Ia_in": ia, "Ia_prior_in": prior_m, "status": st, "Q0_cfs": ev.Q0, **loc,
                         "nse_dist": m.nse(target, sim), "nse_total": m.nse(ev.Q_obs, sim + base),
                         "TE": tm["TE"], "timing_error_h": tm["EMD_h"],
                         "centroid_shift_h": tm["centroid_shift_h"],
                         "peak_obs_cfs": ev.Q_obs.max(), "peak_dist_cfs": (sim + base).max()})
        return d.DistFit(p, list(self.input_events), self.cells, pd.DataFrame(rows), self.router,
                         self.dt, self.kb_days, None)


def _forecast(ev, mu, P, res, rng, n_samples, err_sd):
    """Central forecast (mean parameters, Ia from the regression) and its 90 % interval."""
    nm = res.n_model
    ptot = storm_rain_max(ev)
    z = res.z(ev)
    ia0 = float(np.clip(mu[-2] + mu[-1] * z, 0.0, ptot))
    p0 = d._unpack(mu[:nm], res.a_imp, res.d_imp, res.use_gw)
    sim, target, base = simulate(ev, p0, ia0, res.router, res.dt, res.kb_days)
    q = sim + base
    band = None
    if n_samples:
        L = np.linalg.cholesky(P + 1e-12 * np.eye(len(mu)))
        qs = []
        for _ in range(n_samples):
            x_ = np.clip(mu + L @ rng.standard_normal(len(mu)), res.lo, res.hi)
            ia_ = float(np.clip(x_[-2] + x_[-1] * z + res.tau_ia * rng.standard_normal(), 0.0, ptot))
            s_, _, b_ = simulate(ev, d._unpack(x_[:nm], res.a_imp, res.d_imp, res.use_gw), ia_,
                                 res.router, res.dt, res.kb_days)
            qs.append(s_ + b_)
        q5, q95 = np.percentile(np.array(qs), [5, 95], axis=0)
        err = 1.645 * err_sd * max(target.max(), 1e-6)
        band = np.vstack([np.maximum(q - np.hypot(q - q5, err), 0.0), q + np.hypot(q95 - q, err)])
    return {"time": ev.time, "Q_obs": ev.Q_obs, "Q_forecast": q, "band": band, "recession": base,
            "Ia_forecast": ia0, "target": target, "sim": sim}


def sequential_update(events, cells, dt: float, gauge_area_mi2: float, kb_days: Optional[float],
                      a_imp: Optional[float] = None, hill_exp: float = 0.0,
                      prior: Optional[dict] = None, tau_ia: float = 0.35, drift: float = 0.0,
                      n_samples: int = 30, s0: float = 0.05, max_nfev: int = 400, seed: int = 0,
                      batch_fit=None, router=None, verbose: bool = True) -> SequentialResult:
    """Forecast and update for each storm in date order (update_storm).
    Further storms can be added with res.update_storm(storm).

    events    : storms in any order; processed in date order
    prior     : {name: (mean, sd)} in estimation units; defaults for missing names
    tau_ia    : sd (in) of Ia about ia_mean + ia_slope z
    drift     : fraction of the prior covariance added before each update
    n_samples : parameter samples per 90 % interval (0 = none)
    s0        : initial residual sd (peak-normalised)
    batch_fit : optional DistFit for comparison"""
    use_gw = kb_days is not None
    names, lo, hi = param_names(a_imp, use_gw)
    router = router or d.Router(cells, dt, hill_exp=hill_exp)
    pr = {**default_prior(names), **(prior or {})}     # missing names take the default prior
    m0 = np.array([pr[k][0] for k in names], float)
    P0 = np.diag([pr[k][1] ** 2 for k in names])
    order = np.argsort([ev.time[0] for ev in events], kind="stable")
    lq = np.log10([max(ev.q0(kb_days) if use_gw else ev.Q0, 1e-3) for ev in events])
    zq = (float(lq.mean()), float(lq.std()) if lq.std() > 0 else 1.0)
    res = SequentialResult(names, lo, hi, m0, P0, [np.clip(m0, lo + 1e-9, hi - 1e-9)], [P0.copy()],
                           pd.DataFrame(), [], router, [], np.array([], int), list(events), cells, dt,
                           gauge_area_mi2, kb_days, a_imp, tau_ia, zq)
    res.settings = {"drift": drift, "n_samples": n_samples, "s0": s0, "max_nfev": max_nfev}
    res.state = {"s2": s0 ** 2, "seen_sd": [], "rng": np.random.default_rng(seed)}
    for i in order:
        res.update_storm(events[i], verbose=verbose)
    if batch_fit is not None:
        res.batch_x = d._pack(batch_fit.params, a_imp, use_gw)
    return res


def _update_storm(res: SequentialResult, ev, verbose: bool = True) -> dict:
    """One sequential step for storm ev:
    1. Forecasted flow from the current prior (Ia from the regression, and 90 % interval);
    2. update: MAP of the joint posterior of (theta, Ia_k), Laplace covariance,
       and a 90 % interval for the posterior hydrograph;
    3. Store the posterior as the prior for the next storm."""
    S, st = res.settings, res.state
    rng, dt, kb_days, a_imp, router = st["rng"], res.dt, res.kb_days, res.a_imp, res.router
    use_gw, nm, tau_ia = res.use_gw, res.n_model, res.tau_ia
    lo, hi = res.lo, res.hi
    k = len(res.history)
    m_, P = res.means[-1].copy(), res.covs[-1].copy()
    if S["drift"] > 0:
        P = P + S["drift"] * res.prior_cov
    # ---- 1. forecast: parameters from the current prior, Ia from the regression
    fc = _forecast(ev, m_, P, res, rng, S["n_samples"],
                   np.median(st["seen_sd"]) if st["seen_sd"] else S["s0"])
    fm = d.flow_metrics(ev.Q_obs, fc["Q_forecast"], dt)
    tm = d.timing_metrics(ev.Q_obs, fc["Q_forecast"], dt, base=fc["recession"])
    z = res.z(ev)
    row = {"storm": k + 1, "start": ev.time[0], "used_for_update": True, "z_logQ0": z,
           "Ia_forecast_in": fc["Ia_forecast"],
           "NSE_forecast": fm["NSE"], "KGE_forecast": fm["KGE"], "TE_forecast": tm["TE"],
           "timing_err_forecast_h": tm["EMD_h"], "vol_err_forecast_%": fm["vol_err_pct"],
           "peak_err_forecast_%": fm["peak_err_pct"]}
    if fc["band"] is not None:
        row["obs_inside_90%_band"] = float(np.mean((ev.Q_obs >= fc["band"][0]) & (ev.Q_obs <= fc["band"][1])))
    # ---- 2. update: joint normal prior of (theta, Ia_k), MAP, Laplace covariance
    ptot = storm_rain_max(ev)
    H = np.zeros(len(m_)); H[-2], H[-1] = 1.0, z
    m_aug = np.r_[m_, H @ m_]
    P_aug = np.block([[P, (P @ H)[:, None]], [(H @ P)[None, :], np.array([[H @ P @ H + tau_ia ** 2]])]])
    lo_a, hi_a = np.r_[lo, 0.0], np.r_[hi, max(ptot, 1e-3)]
    Pinv = np.linalg.inv(P_aug)
    Lp = np.linalg.cholesky(0.5 * (Pinv + Pinv.T))

    def r_of(phi):
        p_ = d._unpack(phi[:nm], a_imp, 0.05, use_gw)
        sim, target, _ = simulate(ev, p_, phi[-1], router, dt, kb_days)
        return (sim - target) / max(target.max(), 1e-6)

    s2 = st["s2"]
    x_ = np.clip(m_aug, lo_a + 1e-9, hi_a - 1e-9)
    # Initial Ia: best of a 13-point grid on [0, storm rainfall]. The objective is
    # flat where Ia exceeds the rainfall, and a local search started there stalls.
    # The grid sets the starting point only.
    def _obj_ia(ia):
        ph = x_.copy(); ph[-1] = ia
        return np.sum(r_of(ph) ** 2) / s2 + float(np.sum((Lp.T @ (ph - m_aug)) ** 2))
    grid = np.linspace(0.0, 0.95 * hi_a[-1], 13)
    x_[-1] = float(grid[int(np.argmin([_obj_ia(g) for g in grid]))])
    for _ in range(2):        # repeat once if s changed by more than 25 %
        s = np.sqrt(s2)
        sol = optimize.least_squares(lambda ph: np.concatenate([r_of(ph) / s, Lp.T @ (ph - m_aug)]),
                                     x_, bounds=(lo_a, hi_a), x_scale="jac", max_nfev=S["max_nfev"])
        x_ = sol.x
        r = r_of(x_)
        s2_new, sigma2, rho = _noise(r)
        done = abs(np.sqrt(s2_new / s2) - 1) < 0.25
        s2 = s2_new
        if done:
            break
    J = _jacobian(r_of, x_, lo_a, hi_a, r)
    Pa_new = np.linalg.inv(J.T @ J / s2 + Pinv)
    Pa_new = 0.5 * (Pa_new + Pa_new.T)
    st["s2"] = s2
    st["seen_sd"].append(np.sqrt(sigma2))
    sim, target, base = simulate(ev, d._unpack(x_[:nm], a_imp, 0.05, use_gw), x_[-1], router, dt, kb_days)
    q_after = sim + base
    # 90 % interval of the posterior hydrograph: samples of (theta, Ia_k) from the
    # joint posterior, combined in quadrature with this storm's residual sd
    band_after = None
    if S["n_samples"]:
        La = np.linalg.cholesky(Pa_new + 1e-12 * np.eye(len(x_)))
        qs = []
        for _ in range(S["n_samples"]):
            ph = np.clip(x_ + La @ rng.standard_normal(len(x_)), lo_a, hi_a)
            s_, _, b_ = simulate(ev, d._unpack(ph[:nm], a_imp, 0.05, use_gw), ph[-1], router, dt, kb_days)
            qs.append(s_ + b_)
        q5, q95 = np.percentile(np.array(qs), [5, 95], axis=0)
        err = 1.645 * np.sqrt(sigma2) * max(target.max(), 1e-6)
        band_after = np.vstack([np.maximum(q_after - np.hypot(q_after - q5, err), 0.0),
                                q_after + np.hypot(q95 - q_after, err)])
        row["obs_inside_90%_band_after"] = float(np.mean((ev.Q_obs >= band_after[0]) & (ev.Q_obs <= band_after[1])))
    row.update({"Ia_posterior_in": x_[-1], "Ia_posterior_sd": float(np.sqrt(Pa_new[-1, -1])),
                "NSE_after_update": m.nse(ev.Q_obs, q_after), "resid_sd": np.sqrt(sigma2),
                "resid_lag1_corr": rho, "s2": s2, "effective_points": len(r) * (1 - rho) / (1 + rho)})
    m_new, P_new = x_[:-1].copy(), Pa_new[:-1, :-1].copy()
    sd = np.sqrt(np.diag(P_new))
    for j, nme in enumerate(res.names):
        row[f"{nme}_mean"], row[f"{nme}_sd"] = m_new[j], sd[j]
    # ---- 3. posterior is the prior for the next storm
    res.means.append(m_new); res.covs.append(P_new)
    res.history = pd.concat([res.history, pd.DataFrame([row])], ignore_index=True)
    fc.update({"Q_after": q_after, "band_after": band_after, "Ia_after": float(x_[-1]),
               "rain": ev.rain_cells @ res.cells.area_mi2.values / res.cells.area_mi2.sum() / dt})
    res.forecasts.append(fc)
    res.events.append(ev)
    if not any(ev is e for e in res.input_events):
        res.input_events.append(ev)
    res.order = np.r_[res.order, [i for i, e in enumerate(res.input_events) if e is ev][0]].astype(int)
    if verbose:
        print(f"  storm {k + 1:2d} {ev.time[0]:%Y-%m-%d}: forecast NSE {fm['NSE']:6.2f} "
              f"(TE {tm['TE']:5.2f}), posterior NSE {row['NSE_after_update']:5.2f}; "
              f"Ia prior {fc['Ia_forecast']:.2f} in, posterior {x_[-1]:.2f} in")
    return fc


def run_saved(events, cells, dt, folder: str = "data/fits", label: str = "bayes",
              reuse: bool = True, **kwargs) -> SequentialResult:
    """sequential_update with on-disk caching, uses a run with the same storms, cells
    and settings loaded from `folder`; reuse=False forces recomputation."""
    import pickle
    os.makedirs(folder, exist_ok=True)
    key_args = {k: v for k, v in kwargs.items() if k not in ("batch_fit", "router")}
    key_args["prior"] = repr(sorted((kwargs.get("prior") or {}).items()))
    key = d._fit_key(events, cells, {"dt": dt, "method": "sequential_bayes_v6", **key_args})
    path = os.path.join(folder, f"{label}_{key}.pkl")
    if reuse and os.path.exists(path):
        with open(path, "rb") as fh:
            res = pickle.load(fh)
        print(f"loaded saved run '{label}' ({len(res.history)} storms) from {path}; "
              f"set REUSE_SAVED_RUN = False to recompute")
        return res
    res = sequential_update(events, cells, dt, **kwargs)
    with open(path, "wb") as fh:
        pickle.dump(res, fh)
    print(f"saved run '{label}' to {path}")
    return res


