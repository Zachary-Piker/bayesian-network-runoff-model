    C = P / np.outer(s, s)
    if ax is None:
        _, ax = plt.subplots(figsize=(6.6, 5.6))
    im = ax.imshow(C, cmap="RdBu_r", vmin=-1, vmax=1)
    labs = [PARAM_INFO[n][0] for n in res.names]
    ax.set_xticks(range(len(labs)), labs, rotation=45, ha="right"); ax.set_yticks(range(len(labs)), labs)
    for i in range(len(labs)):
        for j in range(len(labs)):
            ax.text(j, i, f"{C[i, j]:.2f}", ha="center", va="center", fontsize=8,
                    color="w" if abs(C[i, j]) > 0.6 else "k")
    plt.colorbar(im, ax=ax, shrink=0.85, label="correlation")
    ax.set_title("Final posterior correlation\n(D, k_hill, k_gw in log10)", fontsize=11)
    return ax


