def forecast_scores(fc: dict, dt: float) -> dict:
    """NSE, KGE, timing efficiency, timing error, peak and volume error of a
    forecast (res.forecasts[k] or res.predict), and coverage of its 90 %
    interval."""
    fm = d.flow_metrics(fc["Q_obs"], fc["Q_forecast"], dt)
    tm = d.timing_metrics(fc["Q_obs"], fc["Q_forecast"], dt, base=fc["recession"])
    out = {"NSE": fm["NSE"], "KGE": fm["KGE"], "TE": tm["TE"], "timing_err_h": tm["EMD_h"],
           "peak_err_%": fm["peak_err_pct"], "vol_err_%": fm["vol_err_pct"], "Ia_used_in": fc["Ia_forecast"]}
    if fc.get("band") is not None:
        b = fc["band"]
        out["obs_inside_90%_band"] = float(np.mean((fc["Q_obs"] >= b[0]) & (fc["Q_obs"] <= b[1])))
    return out


