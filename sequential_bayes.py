def posterior_table(res: SequentialResult) -> pd.DataFrame:
    """Starting prior and final posterior (mean, 90 % interval) in physical units, and
    posterior sd as a percentage of prior sd."""
    rows = []
    mF, sF = res.means[-1], res.sd(-1)
    s0 = np.sqrt(np.diag(res.prior_cov))
    for j, nm in enumerate(res.names):
        lab, unit, _ = PARAM_INFO[nm]
        row = {"parameter": lab, "units": unit,
               "prior_mean": float(to_physical(nm, res.prior_mean[j])),
               "prior_5%": float(to_physical(nm, res.prior_mean[j] - 1.645 * s0[j])),
               "prior_95%": float(to_physical(nm, res.prior_mean[j] + 1.645 * s0[j])),
               "posterior_mean": float(to_physical(nm, mF[j])),
               "posterior_5%": float(to_physical(nm, mF[j] - 1.645 * sF[j])),
               "posterior_95%": float(to_physical(nm, mF[j] + 1.645 * sF[j])),
               "posterior_sd_%_of_prior": 100 * sF[j] / s0[j]}
        if res.batch_x is not None and j < res.n_model:
            row["least_squares_fit"] = float(to_physical(nm, res.batch_x[j]))
        rows.append(row)
    return pd.DataFrame(rows).set_index("parameter")


