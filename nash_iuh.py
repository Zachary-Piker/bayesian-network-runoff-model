def separate_baseflow(Q, method: str = "straight_line", alpha: float = 0.98,
                      passes: int = 3):
    """Split flow into (baseflow, direct runoff), both arrays in cfs.

    straight_line : line from first to last value of the window. Trim the
                    window to (start of rise) -> (end of direct runoff).
    constant      : baseflow = first value of the window.
    lyne_hollick  : recursive digital filter, forward/backward passes.
                    alpha ~0.925 for daily data, ~0.98-0.995 for 15-min data.
    """
    Q = np.asarray(Q, float)
    if method == "constant":
        bf = np.full_like(Q, Q[0])
    elif method == "straight_line":
        bf = np.linspace(Q[0], Q[-1], len(Q))
    elif method == "lyne_hollick":
        bf = Q.copy()
        for p in range(passes):
            x = bf if p % 2 == 0 else bf[::-1]
            qf = np.zeros_like(x)
            for i in range(1, len(x)):
                qf[i] = alpha * qf[i - 1] + 0.5 * (1 + alpha) * (x[i] - x[i - 1])
                qf[i] = min(max(qf[i], 0.0), x[i])
            out = x - qf
            bf = out if p % 2 == 0 else out[::-1]
    else:
        raise ValueError(method)
    bf = np.minimum(bf, Q)
    return bf, Q - bf


def direct_runoff_duration_days(area_mi2: float) -> float:
    """Linsley rule of thumb: direct runoff ends N = A^0.2 days after the peak."""
    return area_mi2 ** 0.2


def monthly_baseflow(daily_q: pd.Series, alpha: float = 0.925,
                     stat: str = "median") -> pd.Series:
    """Monthly baseflow statistic (cfs) from a daily record, using the 3-pass
    Lyne-Hollick filter. For hypothetical storms."""
    q = daily_q.dropna()
    bf, _ = separate_baseflow(q.values, "lyne_hollick", alpha=alpha, passes=3)
    bf = pd.Series(bf, index=q.index)
    out = bf.groupby(bf.index.month).agg(stat)
    out.index.name = "month"
    out.attrs["baseflow_index"] = float(bf.sum() / q.sum())
    return out


def recession_constant(q: pd.Series, min_days: int = 5, skip_days: int = 2) -> float:
    """Baseflow recession constant k_b (days) from a daily series,
    Q(t) = Q0 exp(-t/k_b): median over recession runs."""
    v = q.dropna().values
    dec = np.diff(v) < 0
    ks, run = [], 0
    for i, d in enumerate(dec):
        run = run + 1 if d else 0
        if run >= min_days and run > skip_days and v[i + 1] > 0 and v[i] > 0:
            ks.append(-1.0 / np.log(v[i + 1] / v[i]))
    return float(np.median(ks)) if ks else np.nan


def exponential_baseflow(Q0: float, kb_days: float):
    """Callable baseflow(t_hours) = Q0 exp(-t/k_b) for simulate(baseflow=...)."""
    return lambda t: Q0 * np.exp(-np.asarray(t) / (24.0 * kb_days))


