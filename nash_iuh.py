def _clean_series(times, values, utc: bool = True) -> pd.Series:
    t = pd.to_datetime(pd.Series(times), utc=utc)
    if utc:
        t = t.dt.tz_convert("UTC").dt.tz_localize(None)
    s = pd.Series(pd.to_numeric(pd.Series(values), errors="coerce").values,
                  index=pd.DatetimeIndex(t), name="Q_cfs").sort_index()
    return s[~s.index.duplicated()].dropna()


def load_usgs_csv(path: str) -> pd.Series:
    """Load a CSV downloaded from the USGS Water Data site or API (columns
    'time' and 'value'). Returns cfs indexed by UTC time."""
    df = pd.read_csv(path)
    tcol = next(c for c in df.columns if c.lower() in ("time", "datetime", "timestamp"))
    vcol = next(c for c in df.columns if c.lower() in ("value", "result", "discharge"))
    return _clean_series(df[tcol], df[vcol])


def load_usgs_rdb(path: str, tz_col: str = "tz_cd") -> pd.Series:
    """Load a legacy NWIS RDB file (tab-delimited). Converts local time to UTC
    using the tz_cd column (CST/CDT)."""
    df = pd.read_csv(path, sep="\t", comment="#", dtype=str).iloc[1:]
    qcol = next(c for c in df.columns if "_00060" in c and not c.endswith("_cd"))
    offs = {"CST": 6, "CDT": 5, "UTC": 0}
    t = pd.to_datetime(df["datetime"])
    if tz_col in df:
        t = t + pd.to_timedelta(df[tz_col].map(offs).fillna(0), unit="h")
    return _clean_series(t.values, df[qcol].values, utc=False)


def load_iem_hourly_precip(path: str, stations: Optional[Sequence[str]] = None) -> pd.Series:
    """Load the IEM 'Hourly Precipitation' CSV (choose UTC when downloading).
    Hourly totals in inches. For several stations, returns the arithmetic
    mean (no Thiessen weighting)."""
    df = pd.read_csv(path)
    tcol = next(c for c in df.columns if "valid" in c.lower())
    pcol = next(c for c in df.columns if "precip" in c.lower())
    df[pcol] = pd.to_numeric(df[pcol], errors="coerce")   # 'M' (missing) -> NaN
    df[tcol] = pd.to_datetime(df[tcol])
    if "station" not in df:
        df["station"] = "gauge"
    if stations is not None:
        df = df[df["station"].isin(stations)]
    wide = df.groupby([tcol, "station"])[pcol].sum(min_count=1).unstack()
    s = wide.mean(axis=1, skipna=True).fillna(0.0)   # average of stations reporting
    s.index.name = "time"
    return s.rename("rain_in").sort_index()


def load_basin_geojson(path: str) -> np.ndarray:
    """Outer ring (lon, lat) of a basin polygon from a GeoJSON file
    (e.g. the NLDI basin or a StreamStats delineation)."""
    import json
    with open(path) as fh:
        g = json.load(fh)
    geom = g["features"][0]["geometry"] if g.get("type") == "FeatureCollection" else \
        g.get("geometry", g)
    coords = geom["coordinates"]
    ring = coords[0] if geom["type"] == "Polygon" else max(
        (p[0] for p in coords), key=len)
    return np.asarray(ring, float)


def basin_average(grid_stack: np.ndarray, lats: np.ndarray, lons: np.ndarray,
                  basin_ring: np.ndarray) -> np.ndarray:
    """Basin-average rainfall from gridded radar data (e.g. MRMS or Stage IV).

    grid_stack : (time, ny, nx) rainfall per step (in; from mm divide by 25.4)
    lats, lons : 2-D (ny, nx) cell-center coordinates (lons in -180..180)
    basin_ring : (m, 2) lon/lat polygon from load_basin_geojson
    Returns an array (time,) of basin-mean rainfall.
    """
    from matplotlib.path import Path
    inside = Path(basin_ring).contains_points(
        np.column_stack([lons.ravel(), lats.ravel()])).reshape(lats.shape)
    if not inside.any():
        raise ValueError("no grid cells inside the basin; check the longitude convention and extent")
    return np.nanmean(np.asarray(grid_stack)[:, inside], axis=1)


def to_common_grid(rain: pd.Series, flow: pd.Series, dt_minutes: int = 15,
                   rain_is_hourly: bool = True) -> tuple[pd.Series, pd.Series]:
    """Put rain (depth per record) and flow (cfs) on one regular UTC grid.

    Flow: interpolated to grid times (gaps up to 2 h filled).
    Rain: hourly totals (labelled at hour END, as IEM does) are spread evenly
          over the sub-steps of that hour; finer rain is summed into steps.
    """
    rule = f"{dt_minutes}min"
    start = max(rain.index.min(), flow.index.min()).ceil(rule)
    end = min(rain.index.max(), flow.index.max()).floor(rule)
    grid = pd.date_range(start, end, freq=rule)

    f = flow.reindex(flow.index.union(grid)).interpolate(
        method="time", limit=int(120 / dt_minutes)).reindex(grid)

    if rain_is_hourly and dt_minutes < 60:
        per = 60 // dt_minutes
        r_h = rain.resample("1h", label="right", closed="right").sum()
        r = r_h.reindex(grid, method="bfill") / per
    else:
        r = rain.resample(rule, label="right", closed="right").sum().reindex(grid)
    return r.fillna(0.0).rename("rain_in"), f.rename("Q_cfs")


