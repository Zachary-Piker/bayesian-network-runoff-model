# 6. Hydrograph comparison (validation and flow-control analysis) - Unused in the 2 jupyter notebooks
# ---------------------------------------------------------------------------------------------------

def compare_hydrographs(obs, sim, dt: float = 0.25) -> dict:
    """Mismatch metrics between observed and simulated flow on the same grid.

    Signatures of upstream flow control (dams, detention, diversions) often show
    up as: peak_ratio < 1 (attenuated peak), timing_error_h > 0 (late peak),
    volume_ratio != 1 (storage/diversion), longer recession, and low
    correlation with structured (non-random) residuals.
    """
    o, s = np.asarray(obs, float), np.asarray(sim, float)
    r = np.corrcoef(o, s)[0, 1]
    a, b = s.std() / o.std(), s.mean() / o.mean()
    t = np.arange(len(o)) * dt
    cen = lambda x: np.sum(t * x) / np.sum(x)
    return {
        "nse": nse(o, s),
        "kge": float(1 - np.sqrt((r - 1) ** 2 + (a - 1) ** 2 + (b - 1) ** 2)),
        "r": float(r),
        "peak_ratio_obs_over_sim": float(o.max() / s.max()),
        "timing_error_h": float((np.argmax(o) - np.argmax(s)) * dt),
        "volume_ratio_obs_over_sim": float(o.sum() / s.sum()),
        "centroid_shift_h": float(cen(o) - cen(s)),
        "residual_lag1_autocorr": float(pd.Series(o - s).autocorr(1)),
    }


