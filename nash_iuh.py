def event_response_lags(events: Sequence[EventFit]) -> pd.DataFrame:
    """Observed response timing of each event: lag from maximum rainfall step
    to peak, lag from rainfall centroid to peak, and rise time (10 % of peak
    to peak). Negative or very long lags indicate that the rainfall record does
    not explain the hydrograph. Also used to set lag bounds in fit_two_path."""
    rows = []
    for f in events:
        hrs = np.asarray((f.time - f.time[0]) / pd.Timedelta(hours=1))
        q = f.Q_direct_obs
        ip = int(np.argmax(q))
        irise = int(np.argmax(q > 0.1 * q.max()))
        rows.append({"start": f.time[0], "month": f.time[0].month, "rain_in": f.rain_in,
                     "max_rain_in_h": float(f.rain.max() / (hrs[1] - hrs[0])),
                     "runoff_ratio": f.runoff_ratio, "peak_cfs": float(f.Q_obs.max()),
                     "lag_maxrain_to_peak_h": hrs[ip] - hrs[int(np.argmax(f.rain))],
                     "lag_centroid_to_peak_h": hrs[ip] - np.sum(hrs * f.rain) / f.rain.sum(),
                     "rise_time_h": hrs[ip] - hrs[irise]})
    return pd.DataFrame(rows)


def antecedent_rain(rain: pd.Series, start, days: float = 7.0) -> float:
    """Rain (in) that fell in the `days` before `start` (antecedent precipitation)."""
    s = pd.Timestamp(start)
    return float(rain.loc[s - pd.Timedelta(days=days): s - pd.Timedelta(minutes=1)].sum())


@dataclass
class IaRelation:
    """Ia = b0 + b1*ln(Q0) + b2*API  (clipped at >= 0), fitted by least squares.
    Q0 = pre-storm flow (cfs), an antecedent-wetness index.
    API = antecedent precipitation (in)."""
    coef: np.ndarray
    r2: float
    use_api: bool

    def predict(self, Q0_cfs: float, api_in: float = 0.0) -> float:
        x = [1.0, np.log(max(Q0_cfs, 1e-3))] + ([api_in] if self.use_api else [])
        return float(max(np.dot(self.coef, x), 0.0))

    def __repr__(self):
        terms = f"{self.coef[0]:.3f} {self.coef[1]:+.3f}*ln(Q0)"
        if self.use_api:
            terms += f" {self.coef[2]:+.3f}*API"
        return f"Ia = {terms}   (R^2 = {self.r2:.2f})"


def fit_ia_relation(table: pd.DataFrame, api: Optional[Sequence[float]] = None) -> IaRelation:
    """Regress calibrated event Ia on pre-event flow (and optionally API).
    Only events with status == 'ok' are used."""
    ok = (table.status == "ok").values
    y = table.Ia_in.values[ok]
    X = [np.ones(ok.sum()), np.log(np.maximum(table.Q0_cfs.values[ok], 1e-3))]
    if api is not None:
        X.append(np.asarray(api, float)[ok])
    X = np.column_stack(X)
    coef, *_ = np.linalg.lstsq(X, y, rcond=None)
    yhat = X @ coef
    r2 = 1 - np.sum((y - yhat) ** 2) / max(np.sum((y - y.mean()) ** 2), 1e-12)
    return IaRelation(coef, float(r2), api is not None)


# ---------------------------------------------------------------------------------------
# 10. Two-pathway model (fast + slow source areas); used by clear_creek_two_pathway.ipynb
# ---------------------------------------------------------------------------------------
#   rain P(t) ─┬─ fast area (fraction a): impervious or near-channel.
#              │    depression storage d_imp, then all rainfall runs off
#              │    ──► Nash(n_f, k_f)
#              └─ slow area (1-a): pervious soils.
#                   initial abstraction Ia (event-specific, antecedent wetness)
#                   then constant loss rate fc (shared) ──► Nash(n_s, k_s)
#   Q = Q_fast + Q_slow + baseflow
#
#   The catchment IUH is a mixture of two gamma distributions weighted by the
#   runoff from each area. It can be bimodal and varies with antecedent
#   wetness, unlike a single IUH.
# ---------------------------------------------------------------------------------------

@dataclass
class TwoPathParams:
    a_fast: float          # fraction of basin area that responds fast (0-1)
    fc: float              # pervious constant loss rate, in/h
    n_fast: float
    k_fast: float          # h
    n_slow: float
    k_slow: float          # h
    d_imp: float = 0.05    # depression storage on the fast area, in

    @property
    def lag_fast(self):
        return self.n_fast * self.k_fast

    @property
    def lag_slow(self):
        return self.n_slow * self.k_slow

    def as_dict(self):
        return {"a_fast": self.a_fast, "fc_in_h": self.fc, "n_fast": self.n_fast,
                "k_fast_h": self.k_fast, "lag_fast_h": self.lag_fast,
                "n_slow": self.n_slow, "k_slow_h": self.k_slow,
                "lag_slow_h": self.lag_slow, "d_imp_in": self.d_imp}


def fast_area_excess(rain, d_imp: float = 0.05):
    """Excess on the fast area (in/step per unit fast area): all rainfall after
    d_imp inches of depression storage."""
    cum = np.cumsum(np.asarray(rain, float))
    return np.diff(np.maximum(cum - d_imp, 0.0), prepend=0.0)


def slow_area_excess(rain, Ia: float, fc: float, dt: float):
    """Initial-and-constant loss on the pervious area (in/step per unit slow
    area): the first Ia inches are abstracted, then fc*dt per step."""
    P = np.asarray(rain, float)
    after_ia = np.minimum(P, np.maximum(np.cumsum(P) - Ia, 0.0))
    return np.maximum(after_ia - fc * dt, 0.0)


def two_path_excess(rain, p: TwoPathParams, Ia: float, dt: float):
    """Basin-averaged effective rainfall of each pathway (in/step over the basin)."""
    return (p.a_fast * fast_area_excess(rain, p.d_imp),
            (1.0 - p.a_fast) * slow_area_excess(rain, Ia, p.fc, dt))


def solve_ia_for_volume(rain, p: TwoPathParams, runoff_in: float, dt: float):
    """Event initial abstraction Ia (in) so modelled runoff volume == observed.
    Returns (Ia, status). status != 'ok' means no Ia can close the volume
    (the fast area alone already makes too much runoff, or fc is too large)."""
    P = np.asarray(rain, float)
    vf = p.a_fast * fast_area_excess(P, p.d_imp).sum()
    f = lambda ia: vf + (1 - p.a_fast) * slow_area_excess(P, ia, p.fc, dt).sum() - runoff_in
    ptot = P.sum()
    if f(ptot) >= 0:
        return ptot, "fast_area_too_big"
    if f(0.0) <= 0:
        return 0.0, "losses_too_high"
    return optimize.brentq(f, 0.0, ptot, xtol=1e-6), "ok"


def simulate_two_path(rain, p: TwoPathParams, Ia: float,
                      area_mi2: float = CLEAR_CREEK["area_mi2"], dt: float = 0.25,
                      baseflow=0.0, pad: bool = True, length: Optional[int] = None):
    """Two-pathway model: hydrograph (cfs) for an arbitrary rainfall series.

    Ia : initial abstraction for this storm (in). For a past storm use the value
         from calibration; for a new storm use IaRelation.predict(...).
    Returns DataFrame: t_h, rain, excess_fast, excess_slow, Q_fast, Q_slow,
    baseflow, Q.
    """
    P = np.asarray(rain, float)
    if pad:
        P = np.concatenate([P, np.zeros(len(nash_kernel(p.n_slow, p.k_slow, dt)))])
    if length is not None:
        P = np.pad(P, (0, max(0, length - len(P))))[:length]
    pf, ps = two_path_excess(P, p, Ia, dt)
    qf = route(pf, p.n_fast, p.k_fast, area_mi2, dt)
    qs = route(ps, p.n_slow, p.k_slow, area_mi2, dt)
    t = (np.arange(len(P)) + 1) * dt
    if callable(baseflow):
        bf = np.asarray(baseflow(t), float)
    else:
        bf = np.asarray(baseflow, float)
        bf = np.full(len(P), float(bf)) if bf.ndim == 0 else \
            np.pad(bf, (0, max(0, len(P) - len(bf))), mode="edge")[: len(P)]
    return pd.DataFrame({"t_h": t, "rain": P, "excess_fast": pf, "excess_slow": ps,
                         "Q_fast": qf, "Q_slow": qs, "baseflow": bf,
                         "Q": qf + qs + bf})


@dataclass
class TwoPathFit:
    params: TwoPathParams
    events: list                 # the EventFit objects used (data containers)
    table: pd.DataFrame          # per-event Ia, NSE, peak errors
    cost: float
    area_mi2: float
    dt: float

    def simulate_event(self, i: int) -> pd.DataFrame:
        ev, ia = self.events[i], self.table.Ia_in.iloc[i]
        return simulate_two_path(ev.rain, self.params, ia, self.area_mi2, self.dt,
                                 baseflow=ev.baseflow, pad=False)

    def plot_event(self, i: int, single=None, ax=None):
        """Observed vs two-pathway (with its fast/slow parts) and, if given as
        (n, k), the single-Nash model with the event's own phi."""
        import matplotlib.pyplot as plt
        ev = self.events[i]
        sim = self.simulate_event(i)
        x = ev.time
        if ax is None:
            _, ax = plt.subplots(figsize=(10, 4))
        ax.plot(x, ev.Q_obs, "k-", lw=1.3, label="Observed")
        if single is not None:
            qs = route(ev.excess, single[0], single[1], self.area_mi2, self.dt,
                       len(ev.Q_obs)) + ev.baseflow
            ax.plot(x, qs, color="#d95f02", lw=1.6, ls="--",
                    label=f"Single Nash, shared n,k (NSE {nse(ev.Q_direct_obs, qs - ev.baseflow):.2f})")
        ax.plot(x, sim.Q.values, color="#1b9e77", lw=2.2,
                label=f"Two-pathway (NSE {self.table.nse_two_path.iloc[i]:.2f})")
        ax.fill_between(x, ev.baseflow, ev.baseflow + sim.Q_fast.values,
                        color="#e7298a", alpha=0.25, label="fast part")
        ax.plot(x, ev.baseflow + sim.Q_slow.values, color="#7570b3", lw=1, ls=":",
                label="slow part")
        ax.plot(x, ev.baseflow, color="gray", ls=":", lw=1)
        ax.set_ylabel("Discharge (cfs)")
        ax2 = ax.twinx()
        w = pd.Timedelta(hours=self.dt)
        ax2.bar(x - w, ev.rain / self.dt, width=w, align="edge", color="#9ecae1")
        ax2.set_ylim(max(ev.rain.max() / self.dt, 1e-3) * 3, 0)
        ax2.set_ylabel("Rainfall (in/h)")
        ax.set_title(f"{x[0]:%Y-%m-%d}  Ia = {self.table.Ia_in.iloc[i]:.2f} in")
        ax.legend(fontsize=8, loc="upper right")
        return ax


def _two_path_residuals(x, events, area, dt, a_fixed, d_imp, normalize):
    # parameters are optimised as (n, LAG) for each pathway, k = lag / n,
    # so the lag ranges can be bounded directly
    if a_fixed is None:
        a, fc, nf, lag_f, ns, lag_s = x
    else:
        a = a_fixed
        fc, nf, lag_f, ns, lag_s = x
    kf, ks = lag_f / nf, lag_s / ns
    p = TwoPathParams(a, fc, nf, kf, ns, ks, d_imp)
    res, info = [], []
    for ev in events:
        ia, status = solve_ia_for_volume(ev.rain, p, ev.runoff_in, dt)
        pf, ps = two_path_excess(ev.rain, p, ia, dt)
        L = len(ev.Q_direct_obs)
        sim = route(pf, nf, kf, area, dt, L) + route(ps, ns, ks, area, dt, L)
        w = ev.Q_direct_obs.max() if normalize else 1.0
        res.append((sim - ev.Q_direct_obs) / w)
        info.append((ia, status, sim))
    # keep the pathways ordered even if the lag ranges overlap
    res.append(np.atleast_1d(10.0 * max(0.0, lag_f - 0.8 * lag_s)))
    return np.concatenate(res), p, info


def fit_two_path(events: Sequence[EventFit], area_mi2: float = CLEAR_CREEK["area_mi2"],
                 dt: float = 0.25, a_fast: Optional[float] = None,
                 a_fast_bounds=(0.002, 0.4), d_imp: float = 0.05,
                 fast_lag_bounds=(0.25, 12.0), slow_lag_bounds=(1.0, 60.0),
                 normalize: bool = True, n_starts: int = 8, seed: int = 0) -> TwoPathFit:
    """Jointly calibrate the two-pathway model on several storms.

    Shared by all events : a_fast, fc, n_fast, lag_fast, n_slow, lag_slow
    Per event            : Ia, set by matching the runoff volume
                           (represents antecedent wetness)
    a_fast               : fixed value (e.g. connected impervious fraction from
                           NLCD), or None to fit within a_fast_bounds.
    fast_lag_bounds,
    slow_lag_bounds      : allowed centroid lags n*k (h) of each pathway. Set
                           them from the observed response times
                           (event_response_lags) so the pathways cannot merge
                           into one compromise response.
    Multi-start least squares (the problem has local minima).
    """
    rng = np.random.default_rng(seed)
    lo = [a_fast_bounds[0], 0.0, 0.5, fast_lag_bounds[0], 0.8, slow_lag_bounds[0]]
    hi = [a_fast_bounds[1], 2.0, 8.0, fast_lag_bounds[1], 20.0, slow_lag_bounds[1]]
    mid_f = float(np.sqrt(fast_lag_bounds[0] * fast_lag_bounds[1]))
    mid_s = float(np.clip(np.median([e.lag_h for e in events]), *slow_lag_bounds))
    best = None
    for s in range(n_starts):
        jitter = rng.uniform(0.6, 1.6, 6) if s else np.ones(6)
        x0 = np.array([0.03, 0.10, 1.5, mid_f, 3.0, mid_s]) * jitter
        x0 = np.clip(x0, np.array(lo) + 1e-6, np.array(hi) - 1e-6)
        l, h = lo, hi
        if a_fast is not None:
            x0, l, h = x0[1:], lo[1:], hi[1:]
        sol = optimize.least_squares(
            lambda x: _two_path_residuals(x, events, area_mi2, dt, a_fast, d_imp, normalize)[0],
            x0, bounds=(l, h), x_scale="jac", max_nfev=3000)
        if best is None or sol.cost < best.cost:
            best = sol
    _, p, info = _two_path_residuals(best.x, events, area_mi2, dt, a_fast, d_imp, normalize)
    rows = []
    for ev, (ia, status, sim) in zip(events, info):
        q = sim + ev.baseflow
        rows.append({"start": ev.time[0], "rain_in": ev.rain_in, "runoff_in": ev.runoff_in,
                     "Ia_in": ia, "status": status, "Q0_cfs": ev.Q_obs[0],
                     "nse_single_own_fit": ev.nse,
                     "nse_two_path": nse(ev.Q_direct_obs, sim),
                     "peak_obs_cfs": ev.Q_obs.max(), "peak_two_path_cfs": q.max(),
                     "fast_share_of_runoff": float(
                         p.a_fast * fast_area_excess(ev.rain, p.d_imp).sum()
                         / max(ev.runoff_in, 1e-9))})
    fit = TwoPathFit(p, list(events), pd.DataFrame(rows), float(best.cost), area_mi2, dt)
    at = [abs(p.lag_fast - b) < 0.02 * b for b in fast_lag_bounds] + \
         [abs(p.lag_slow - b) < 0.02 * b for b in slow_lag_bounds]
    if any(at):
        import warnings
        warnings.warn("a fitted lag is at its bound; check the lag range and the events used")
    return fit


# ---------- comparing the two model structures --------------------------------

def pooled_information_criteria(events: Sequence[EventFit], sims: Sequence[np.ndarray],
                                n_global: int) -> dict:
    """AIC / BIC over all events pooled (direct runoff, cfs). n_global = number of
    shared parameters; one volume parameter per event (phi or Ia) is added."""
    obs = np.concatenate([e.Q_direct_obs for e in events])
    sim = np.concatenate(sims)
    N, kpar = len(obs), n_global + len(events)
    sse = float(np.sum((obs - sim) ** 2))
    return {"params": kpar, "N": N, "SSE": sse,
            "AIC": N * np.log(sse / N) + 2 * kpar,
            "BIC": N * np.log(sse / N) + kpar * np.log(N),
            "pooled_NSE": 1 - sse / np.sum((obs - obs.mean()) ** 2)}


def single_nash_sims(events: Sequence[EventFit], n: float, k: float,
                     area_mi2: float = CLEAR_CREEK["area_mi2"], dt: float = 0.25):
    """Direct-runoff simulations of each event with a shared single Nash (n, k)
    and each event's own phi (volume-matched)."""
    return [route(e.excess, n, k, area_mi2, dt, len(e.Q_direct_obs)) for e in events]