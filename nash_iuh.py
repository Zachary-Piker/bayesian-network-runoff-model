def fetch_usgs_iv(site: str = CLEAR_CREEK["site"], start: str = "2015-01-01",
                  end: str = "2016-01-01", parameter: str = "00060",
                  api_key: Optional[str] = None) -> pd.Series:
    """Download 15-minute discharge (cfs, UTC) from the USGS Water Data API
    (OGC 'continuous' collection). Max ~3 years per request; loop over years
    for longer records. Prefers the official `dataretrieval` package if
    installed (pip install dataretrieval), otherwise calls the API directly.
    """
    try:
        from dataretrieval import waterdata
        df, _ = waterdata.get_continuous(monitoring_location_id=f"USGS-{site}",
                                         parameter_code=parameter,
                                         time=f"{start}/{end}")
        return _clean_series(df["time"], df["value"])
    except ImportError:
        pass
    import requests
    last = None
    for ver in ("v1", "v0"):                      # current API version first
        url = f"https://api.waterdata.usgs.gov/ogcapi/{ver}/collections/continuous/items"
        params = {"monitoring_location_id": f"USGS-{site}", "parameter_code": parameter,
                  "time": f"{start}T00:00:00Z/{end}T00:00:00Z", "limit": 50000, "f": "json",
                  "properties": "time,value"}
        if api_key:
            params["api_key"] = api_key
        times, vals = [], []
        try:
            while url:
                r = requests.get(url, params=params, timeout=120)
                r.raise_for_status()
                js = r.json()
                for f in js.get("features", []):
                    times.append(f["properties"]["time"])
                    vals.append(f["properties"]["value"])
                url = next((l["href"] for l in js.get("links", []) if l.get("rel") == "next"), None)
                params = None  # the 'next' link already carries the query
            return _clean_series(times, vals)
        except Exception as e:                    # try the other API version
            last = e
    raise RuntimeError(f"USGS continuous-data request failed: {last}")


