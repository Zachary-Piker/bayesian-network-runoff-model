def find_events(flow: pd.Series, rain: Optional[pd.Series] = None,
                area_mi2: float = CLEAR_CREEK["area_mi2"],
                min_rise_cfs: float = 100.0, lookback_h: float = 48.0,
                months: Sequence[int] = (5, 6, 7, 8, 9, 10)) -> pd.DataFrame:
    """Candidate storm windows from a regular-interval flow Series.

    Peaks with prominence >= min_rise_cfs; window starts at the minimum flow in
    the `lookback_h` before the peak, but not before the previous peak (so two
    storms close together are split at the trough between them), and ends
    N = A^0.2 days after the peak or at the next window's start, whichever is
    first, so a window never ends before its own peak. Default months May-Oct
    exclude snowmelt and frozen ground. Inspect the windows before fitting.
    """
    q = flow.dropna()
    dt = (q.index[1] - q.index[0]) / pd.Timedelta(hours=1)
    peaks, props = signal.find_peaks(q.values, prominence=min_rise_cfs,
                                     distance=int(24 / dt))
    back = int(lookback_h / dt)
    fwd = int(direct_runoff_duration_days(area_mi2) * 24 / dt)
    rows = []
    for j, (p, prom) in enumerate(zip(peaks, props["prominences"])):
        if q.index[p].month not in months:
            continue
        # start at the lowest flow in the lookback, but not before the previous
        # peak: with two storms close together the window starts at the trough
        lo = max(0, p - back, int(peaks[j - 1]) if j > 0 else 0)
        s = lo + int(np.argmin(q.values[lo: p + 1]))
        e = min(len(q) - 1, p + fwd)
        row = {"start": q.index[s], "peak_time": q.index[p], "end": q.index[e],
               "peak_cfs": q.values[p], "rise_cfs": prom}
        if rain is not None:
            row["rain_in"] = float(rain.loc[q.index[s] - pd.Timedelta(hours=12):
                                            q.index[p]].sum())
        rows.append(row)
    ev = pd.DataFrame(rows)
    if len(ev) > 1:  # clip overlapping windows: end where the next window starts
        ev["end"] = np.minimum(ev["end"].values,
                               np.append(ev["start"].values[1:], ev["end"].values[-1]))
    return ev


def extract_event(rain: pd.Series, flow: pd.Series, start, end,
                  rain_lead_h: float = 6.0):
    """Extract rainfall and flow for one event. The window starts `rain_lead_h` before
    `start` so rain that caused the rise is included, and flow is trimmed to
    begin where the window begins."""
    s = pd.Timestamp(start) - pd.Timedelta(hours=rain_lead_h)
    e = pd.Timestamp(end)
    r, q = rain.loc[s:e], flow.loc[s:e]
    idx = r.index.intersection(q.index)
    return r.loc[idx], q.loc[idx]


