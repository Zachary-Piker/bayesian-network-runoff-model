"""
FUNCTIONS GENERATED BY CLAUDE OPUS 5.5

=======================================================================
nash_iuh.py -- Nash-cascade instantaneous unit hydrograph (IUH) toolkit
=======================================================================

Developed for Clear Creek near Coralville, IA (USGS 05454300, 98.1 mi^2).

Model (linear system)
---------------------
    rain P(t) --[loss model]--> effective rain Pe(t)
              --[convolve with Nash IUH u(t; n, k)]--> direct runoff Qd(t)
              --[+ baseflow]--> streamflow Q(t)

    u(t) = t^(n-1) exp(-t/k) / (k^n Gamma(n))      (gamma distribution)
    mean lag = n*k,  variance = n*k^2,  time to peak = (n-1)*k

Units (US customary, as distributed by USGS and IEM):
    rainfall      inches per time step (depth during the step)
    discharge     cfs
    area          mi^2
    time          hours (n is dimensionless, k in hours)
    1 in/h over 1 mi^2 = 645.33 cfs

Time convention: rain[i] fell during (t[i] - dt, t[i]]; flow[i] is the
discharge at t[i]. All times UTC.

Main entry points
-----------------
    simulate(...)            any rainfall -> hydrograph
    unit_hydrograph(...)     D-hour UH for given n, k
    fit_event(...)           one storm  -> n, k, phi
    fit_events_jointly(...)  many storms -> one (n, k) for the catchment
    compare_hydrographs(...) mismatch metrics (for the flow-control study)
    find_events / extract_event                      storm windows from the flow record
    event_response_lags / fit_ia_relation            screening and pre-storm Ia
    fetch_usgs_iv / load_usgs_csv / load_iem_hourly_precip / ...  data I/O

The distributed (stream-network) model in distributed_iuh.py uses this module for
storm selection, the flow side of each storm (fit_event), screening and the
linear-reservoir kernel. Section 10 (two-pathway model) is used only by
clear_creek_two_pathway.ipynb.
"""

