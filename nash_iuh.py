def nse(obs, sim) -> float:
    """Nash-Sutcliffe efficiency."""
    obs, sim = np.asarray(obs, float), np.asarray(sim, float)
    return float(1 - np.sum((obs - sim) ** 2) / np.sum((obs - obs.mean()) ** 2))


def nash_moments(effective_rain, q_direct, dt: float):
    """Method-of-moments (n, k): n*k = centroid lag, n*k^2 = variance difference."""
    def mom(x, offset):
        x = np.asarray(x, float)
        t = np.arange(len(x)) * dt + offset
        m1 = np.sum(t * x) / np.sum(x)
        return m1, np.sum((t - m1) ** 2 * x) / np.sum(x)
    mp, vp = mom(effective_rain, 0.5 * dt)   # rain block midpoints
    mq, vq = mom(q_direct, 1.0 * dt)         # flow at end of steps
    lag = max(mq - mp, 1e-6)
    k = max(vq - vp, 1e-6) / lag
    return lag / k, k


@dataclass
class EventFit:
    n: float
    k: float
    phi: float                  # in/h
    nse: float
    rain_in: float
    runoff_in: float
    time: pd.DatetimeIndex
    rain: np.ndarray
    excess: np.ndarray
    Q_obs: np.ndarray
    baseflow: np.ndarray
    Q_direct_obs: np.ndarray
    Q_direct_sim: np.ndarray
    moments_guess: tuple = field(default=(np.nan, np.nan))

    @property
    def lag_h(self):
        return self.n * self.k

    @property
    def runoff_ratio(self):
        return self.runoff_in / self.rain_in if self.rain_in > 0 else np.nan

    @property
    def Q_sim(self):
        return self.Q_direct_sim + self.baseflow

    def summary(self) -> dict:
        return {"start": self.time[0], "n": self.n, "k_h": self.k, "lag_h": self.lag_h,
                "phi_in_h": self.phi, "rain_in": self.rain_in, "runoff_in": self.runoff_in,
                "runoff_ratio": self.runoff_ratio, "peak_obs_cfs": self.Q_obs.max(),
                "peak_sim_cfs": self.Q_sim.max(), "nse_direct": self.nse,
                "nse_total": nse(self.Q_obs, self.Q_sim)}

    def plot(self, ax=None, title=None):
        import matplotlib.pyplot as plt
        if ax is None:
            _, ax = plt.subplots(figsize=(10, 4))
        x = self.time
        dt_h = (x[1] - x[0]) / pd.Timedelta(hours=1)
        ax.plot(x, self.Q_obs, "k-", lw=1.2, label="Observed Q")
        ax.plot(x, self.Q_sim, color="#d95f02", lw=2, label=f"Nash model (NSE {self.nse:.2f})")
        ax.plot(x, self.baseflow, color="gray", ls=":", label="Baseflow")
        ax.set_ylabel("Discharge (cfs)")
        ax2 = ax.twinx()
        w = pd.Timedelta(hours=dt_h)
        ax2.bar(x - w, self.rain / dt_h, width=w, align="edge", color="#9ecae1", label="Rain")
        ax2.bar(x - w, self.excess / dt_h, width=w, align="edge", color="#3182bd", label="Excess")
        ax2.set_ylim(max(self.rain.max() / dt_h, 1e-3) * 3, 0)
        ax2.set_ylabel("Rainfall (in/h)")
        ax.set_title(title or f"n={self.n:.2f}, k={self.k:.2f} h, lag={self.lag_h:.1f} h, "
                              f"phi={self.phi:.3f} in/h")
        h1, l1 = ax.get_legend_handles_labels()
        h2, l2 = ax2.get_legend_handles_labels()
        ax.legend(h1 + h2, l1 + l2, fontsize=8, loc="upper right")
        return ax


def fit_event(rain, flow, area_mi2: float = CLEAR_CREEK["area_mi2"], dt: float = 0.25,
              baseflow_method: str = "straight_line", time=None, **bf_kwargs) -> EventFit:
    """Fit a Nash IUH to a single storm.

    rain, flow : same length, same time grid (rain in/step, flow cfs). Window
                 should start just before the rise and end when direct runoff
                 ends. pandas Series keep their index.
    Steps: baseflow separation -> runoff depth -> phi by volume matching ->
           method-of-moments guess -> least-squares fit of (n, k).
    """
    if time is None:
        time = rain.index if isinstance(rain, pd.Series) else \
            pd.RangeIndex(len(rain))
    P = np.asarray(rain, float)
    Q = np.asarray(flow, float)
    bf, Qd = separate_baseflow(Q, baseflow_method, **bf_kwargs)

    runoff_in = Qd.sum() * dt / (area_mi2 * CFS_PER_INHR_MI2)
    phi = phi_for_volume(P, runoff_in, dt)
    Pe = phi_index_excess(P, phi, dt)

    n0, k0 = nash_moments(Pe, Qd, dt)
    x0 = [np.clip(n0, 0.6, 30), np.clip(k0, dt / 4, 200)]
    res = optimize.least_squares(
        lambda x: route(Pe, x[0], x[1], area_mi2, dt, len(Qd)) - Qd,
        x0, bounds=([0.5, dt / 20], [50, 500]))
    n, k = res.x
    Qd_sim = route(Pe, n, k, area_mi2, dt, len(Qd))
    return EventFit(n=n, k=k, phi=phi, nse=nse(Qd, Qd_sim), rain_in=P.sum(),
                    runoff_in=runoff_in, time=pd.Index(time), rain=P, excess=Pe,
                    Q_obs=Q, baseflow=bf, Q_direct_obs=Qd, Q_direct_sim=Qd_sim,
                    moments_guess=(n0, k0))


def event_pieces(rain, flow, area_mi2: float = CLEAR_CREEK["area_mi2"], dt: float = 0.25,
                 baseflow_method: str = "straight_line", time=None, **bf_kwargs) -> EventFit:
    """Observed components of a single storm without model fitting: rainfall,
    flow, separated baseflow, direct runoff and runoff depth. Returns an
    EventFit with the Nash fields (n, k, phi, nse, simulated flow) empty."""
    if time is None:
        time = rain.index if isinstance(rain, pd.Series) else pd.RangeIndex(len(rain))
    P = np.asarray(rain, float)
    Q = np.asarray(flow, float)
    bf, Qd = separate_baseflow(Q, baseflow_method, **bf_kwargs)
    runoff_in = Qd.sum() * dt / (area_mi2 * CFS_PER_INHR_MI2)
    return EventFit(n=np.nan, k=np.nan, phi=np.nan, nse=np.nan, rain_in=P.sum(),
                    runoff_in=runoff_in, time=pd.Index(time), rain=P, excess=np.zeros_like(P),
                    Q_obs=Q, baseflow=bf, Q_direct_obs=Qd, Q_direct_sim=np.zeros_like(Qd),
                    moments_guess=(np.nan, np.nan))


def fit_events_jointly(fits: Sequence[EventFit], area_mi2: float = CLEAR_CREEK["area_mi2"],
                       dt: float = 0.25, normalize: bool = True):
    """One (n, k) for the whole catchment from several storms.

    Keeps each event's effective rain (its own phi) and fits a single (n, k)
    to all direct-runoff hydrographs at once. normalize=True divides each
    event's residuals by its peak so that large events do not dominate.
    Returns (n, k, table of per-event NSE using the shared IUH).
    """
    def resid(x):
        r = []
        for f in fits:
            sim = route(f.excess, x[0], x[1], area_mi2, dt, len(f.Q_direct_obs))
            w = f.Q_direct_obs.max() if normalize else 1.0
            r.append((sim - f.Q_direct_obs) / w)
        return np.concatenate(r)
    x0 = [np.median([f.n for f in fits]), np.median([f.k for f in fits])]
    sol = optimize.least_squares(resid, x0, bounds=([0.5, dt / 20], [50, 500]))
    n, k = sol.x
    rows = []
    for f in fits:
        sim = route(f.excess, n, k, area_mi2, dt, len(f.Q_direct_obs))
        rows.append({"start": f.time[0], "nse_own_fit": f.nse,
                     "nse_shared_iuh": nse(f.Q_direct_obs, sim)})
    return n, k, pd.DataFrame(rows)


