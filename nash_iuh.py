# 3. Forward model
# -----------------

def route(effective_rain, n: float, k: float, area_mi2: float, dt: float,
          length: Optional[int] = None):
    """Convolve effective rain (in/step) with the Nash kernel -> direct runoff (cfs)."""
    pe = np.asarray(effective_rain, float)
    h = nash_kernel(n, k, dt)
    L = len(pe) if length is None else length
    q = np.convolve(pe, h)[:L]
    if len(q) < L:
        q = np.pad(q, (0, L - len(q)))
    return q * area_mi2 * CFS_PER_INHR_MI2   # (in/step)*(1/h) = in/h per step


def simulate(rain, n: float, k: float, area_mi2: float = CLEAR_CREEK["area_mi2"],
             dt: float = 0.25, phi: Optional[float] = None,
             cn: Optional[float] = None, effective: bool = False,
             baseflow=0.0, pad: bool = True, index=None) -> pd.DataFrame:
    """Hydrograph for an arbitrary rainfall series.

    rain      : inches per step (array or pandas Series).
    phi / cn  : loss model, one of phi (in/h) or NRCS curve number.
                effective=True means `rain` is already effective rain.
    baseflow  : constant (cfs), array, or callable f(t_hours) -> cfs.
    pad       : extend past the end of the rain so the recession finishes.
    index     : optional DatetimeIndex for the rain; extended if padded.

    Returns a DataFrame: t_h, rain, excess, Q_direct, baseflow, Q.
    """
    if isinstance(rain, pd.Series) and index is None:
        index = rain.index
    P = np.asarray(rain, float)
    n_pad = len(nash_kernel(n, k, dt)) if pad else 0
    P = np.concatenate([P, np.zeros(n_pad)])

    if effective:
        Pe = P.copy()
    elif phi is not None:
        Pe = phi_index_excess(P, phi, dt)
    elif cn is not None:
        Pe = curve_number_excess(P, cn)
    else:
        raise ValueError("give phi=, cn=, or effective=True")

    Qd = route(Pe, n, k, area_mi2, dt)
    t = (np.arange(len(P)) + 1) * dt
    if callable(baseflow):
        bf = np.asarray(baseflow(t), float)
    else:
        bf = np.asarray(baseflow, float)
        bf = np.full(len(P), float(bf)) if bf.ndim == 0 else \
            np.pad(bf, (0, max(0, len(P) - len(bf))), mode="edge")[: len(P)]

    df = pd.DataFrame({"t_h": t, "rain": P, "excess": Pe,
                       "Q_direct": Qd, "baseflow": bf, "Q": Qd + bf})
    if index is not None:
        idx = pd.DatetimeIndex(index)
        step = pd.Timedelta(hours=dt)
        extra = pd.date_range(idx[-1] + step, periods=n_pad, freq=step) if n_pad else []
        df.index = idx.append(pd.DatetimeIndex(extra))
    return df


def unit_hydrograph(n: float, k: float, area_mi2: float = CLEAR_CREEK["area_mi2"],
                    dt: float = 0.25, duration_h: float = 1.0) -> pd.DataFrame:
    """D-hour unit hydrograph: response (cfs) to 1 inch of effective rain
    spread evenly over `duration_h` hours."""
    steps = max(1, int(round(duration_h / dt)))
    return simulate(np.full(steps, 1.0 / steps), n, k, area_mi2, dt,
                    effective=True)[["t_h", "Q_direct"]]


