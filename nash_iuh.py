# 1. The Nash IUH
# ----------------

def nash_iuh(t, n: float, k: float):
    """IUH ordinate u(t) [1/h] for n reservoirs with storage constant k [h]."""
    return stats.gamma.pdf(np.asarray(t, float), a=n, scale=k)


def nash_scurve(t, n: float, k: float):
    """S-curve S(t) = integral of u from 0 to t (response to a unit step)."""
    return stats.gamma.cdf(np.asarray(t, float), a=n, scale=k)


def nash_kernel(n: float, k: float, dt: float, tol: float = 1e-5):
    """Discrete pulse response h[j] [1/h] for rain that is constant within a
    step of length dt [h]:  h[j] = (S((j+1)dt) - S(j dt)) / dt.

    Exact (no discretization error) and mass-conserving: sum(h)*dt = 1.
    The kernel is truncated once S(t) > 1 - tol.
    """
    t_end = stats.gamma.ppf(1.0 - tol, a=n, scale=k)
    m = int(np.ceil(t_end / dt)) + 1
    S = nash_scurve(np.arange(m + 1) * dt, n, k)
    return np.diff(S) / dt


def nash_properties(n: float, k: float) -> dict:
    """Summary statistics of the IUH shape."""
    tp = max(n - 1.0, 0.0) * k
    return {"n": n, "k_h": k, "lag_h": n * k, "time_to_peak_h": tp,
            "peak_per_h": float(nash_iuh(tp, n, k)) if n > 1 else 1.0 / k,
            "std_h": np.sqrt(n) * k}


# --------------------------------------------------------------------
# 2. Loss models: rain (in/step), convert to: effective rain (in/step)
# --------------------------------------------------------------------

def phi_index_excess(rain, phi: float, dt: float):
    """Constant loss rate phi [in/h]."""
    return np.maximum(np.asarray(rain, float) - phi * dt, 0.0)


def curve_number_excess(rain, CN: float, ia_ratio: float = 0.2):
    """NRCS curve number applied to cumulative event rain (inches).

    Event-based: the abstraction resets only at the start of the array, so
    apply it to one storm at a time. On a continuous record the cumulative
    rainfall grows without bound and the runoff ratio tends to 1.
    """
    S = 1000.0 / CN - 10.0
    Ia = ia_ratio * S
    P = np.cumsum(np.asarray(rain, float))
    Q = np.where(P > Ia, (P - Ia) ** 2 / (P - Ia + S), 0.0)
    return np.diff(Q, prepend=0.0)


def phi_for_volume(rain, runoff_depth_in: float, dt: float) -> float:
    """phi [in/h] such that sum(effective rain) == observed runoff depth."""
    rain = np.asarray(rain, float)
    if runoff_depth_in <= 0:
        return rain.max() / dt
    if runoff_depth_in >= rain.sum():
        return 0.0
    f = lambda phi: np.maximum(rain - phi * dt, 0.0).sum() - runoff_depth_in
    return optimize.brentq(f, 0.0, rain.max() / dt)


