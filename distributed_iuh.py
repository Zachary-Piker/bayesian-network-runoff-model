def _unpack(x, a_fixed, d_imp, use_gw):
    x = list(x)
    c, lgD, lgk, fc = x[:4]
    k = 4
    if a_fixed is None:
        a = x[k]; k += 1
    else:
        a = a_fixed
    beta, kgw = (0.0, 72.0)
    if use_gw:
        beta, kgw = x[k], 10 ** x[k + 1]
    return DistParams(c, 10 ** lgD, 10 ** lgk, fc, a, d_imp, beta, kgw)


def _pack(p: DistParams, a_fixed, use_gw) -> np.ndarray:
    """Inverse of _unpack: DistParams -> the optimizer's vector."""
    x = [p.c_ms, np.log10(p.D_m2s), np.log10(p.k_hill_h), p.fc]
    if a_fixed is None:
        x.append(p.a_imp)
    if use_gw:
        x += [p.beta, np.log10(p.k_gw_h)]
    return np.array(x, float)


def _event_sim(ev, p, router, gauge_area, dt, kb_days):
    ia, st = solve_ia_dist(ev, p, router, gauge_area, dt, kb_days)
    n = len(ev.Q_obs)
    pe = cell_excess(ev.rain_cells, p, ia, dt)
    quick = router.route(pe, p, length=n)
    if kb_days is None:
        return ia, st, quick, ev.Q_direct_obs, ev.baseflow
    ret = gw_return_flow(infiltration(ev.rain_cells, pe, router.cells.area_mi2.values), p, dt, n)
    rec = recession(ev.q0(kb_days), n, dt, kb_days)
    return ia, st, quick + ret, ev.Q_obs - rec, rec


def _dist_resid(x, events, router, gauge_area, dt, a_fixed, d_imp, normalize, kb_days, use_gw):
    p = _unpack(x, a_fixed, d_imp, use_gw)
    res, info = [], []
    for ev in events:
        ia, st, sim, target, base = _event_sim(ev, p, router, gauge_area, dt, kb_days)
        w = max(target.max(), 1e-6) if normalize else 1.0
        res.append((sim - target) / w)
        info.append((ia, st, sim, target, base))
    return np.concatenate(res), p, info


def param_space(a_imp=None, use_gw=True, c_bounds=(0.1, 4.0), D_bounds=(5.0, 20000.0),
                k_hill_bounds=(0.1, 48.0), fc_bounds=(0.0, 2.0), a_imp_bounds=(0.0, 0.3),
                beta_bounds=(0.0, 0.6), k_gw_bounds=(6.0, 720.0)):
    """Estimation vector: names, lower and upper bounds, default values and jitter
    scale. D, k_hill and k_gw are estimated in log10. a_imp is omitted when fixed;
    beta and k_gw are omitted without return flow."""
    names = ["c_ms", "log10_D", "log10_k_hill", "fc"]
    lo = [c_bounds[0], np.log10(D_bounds[0]), np.log10(k_hill_bounds[0]), fc_bounds[0]]
    hi = [c_bounds[1], np.log10(D_bounds[1]), np.log10(k_hill_bounds[1]), fc_bounds[1]]
    x0, sd = [0.7, 2.5, 0.3, 0.12], [0.4, 0.6, 0.4, 0.06]
    if a_imp is None:
        names.append("a_imp")
        lo.append(a_imp_bounds[0]); hi.append(a_imp_bounds[1]); x0.append(0.03); sd.append(0.02)
    if use_gw:
        names += ["beta", "log10_k_gw"]
        lo += [beta_bounds[0], np.log10(k_gw_bounds[0])]
        hi += [beta_bounds[1], np.log10(k_gw_bounds[1])]
        x0 += [0.1, np.log10(72.0)]; sd += [0.08, 0.4]
    return names, np.array(lo), np.array(hi), np.array(x0), np.array(sd)


def start_points(lo, hi, x_default, n, design="lhs", sd=None, rng=None):
    """Starting vectors for the multi-start fit; the first is the default vector.
    design="lhs": Latin hypercube over the (transformed) bounds.
    design="jitter": normal perturbations of the default vector (sd)."""
    rng = rng or np.random.default_rng(0)
    lo, hi = np.asarray(lo, float), np.asarray(hi, float)
    pts = [np.clip(np.asarray(x_default, float), lo + 1e-6, hi - 1e-6)]
    k, extra = len(lo), n - 1
    if extra <= 0:
        return pts
    if design == "lhs":
        strata = np.array([rng.permutation(extra) for _ in range(k)]).T
        u = (strata + rng.random((extra, k))) / extra
        pts += list(lo + u * (hi - lo))
    elif design == "jitter":
        for _ in range(extra):
            pts.append(np.clip(pts[0] + rng.normal(0, sd), lo + 1e-6, hi - 1e-6))
    else:
        raise ValueError(design)
    return pts


def fit_distributed(events: Sequence[DistEvent], cells: pd.DataFrame, dt: float = 0.25,
                    gauge_area_mi2: float = m.CLEAR_CREEK["area_mi2"],
                    a_imp: Optional[float] = None, d_imp: float = 0.05,
                    kb_days: Optional[float] = None, fit_return_flow: bool = True,
                    c_bounds=(0.1, 4.0), D_bounds=(5.0, 20000.0), k_hill_bounds=(0.1, 48.0),
                    fc_bounds=(0.0, 2.0), a_imp_bounds=(0.0, 0.3), beta_bounds=(0.0, 0.6),
                    k_gw_bounds=(6.0, 720.0),
                    n_starts: int = 20, min_starts: int = 6, stop_repeats: Optional[int] = 3,
                    rel_tol: float = 0.01, start_design: str = "lhs", seed: int = 0,
                    normalize: bool = True, bin_km: float = 0.5, router=None,
                    hill_exp: float = 0.0, L_floor_km: float = 0.25, n_hill: int = 8,
                    max_nfev: int = 2000, verbose: bool = False,
                    fixed_params: Optional[DistParams] = None,
                    start_log: Optional[pd.DataFrame] = None) -> DistFit:
    """Jointly calibrate the distributed model on several storms.

    Shared by all storms : c, D, k_hill, fc, a (unless a_imp is given) and,
                           with baseflow modelling, beta and k_gw.
    One per storm        : Ia, solved by volume matching inside every evaluation.

    kb_days None : fit to straight-line-separated direct runoff.
    kb_days set  : fit to the observed hydrograph with modelled baseflow:
                   Q = Q0 exp(-t/k_b) + quick runoff + event return flow.

    Optimizer: scipy.optimize.least_squares (trust-region reflective, bounded,
    finite-difference Jacobian) on residuals (sim - target) / storm peak, run
    from several starting points (see start_points). Multi-start control:
        n_starts     : maximum number of starts
        min_starts   : minimum number of starts
        stop_repeats : stop early once this many starts have reached the best
                       sum of squares to within rel_tol (None = run all n_starts)
    Every start is recorded in DistFit.starts (SSE, parameters, evaluations).

    Hillslope residence time by distance to the stream (no additional parameter):
        hill_exp = 0 : uniform k_hill
        hill_exp = 1 : k_i = k_hill * L_hill_i / Lbar (see hill_scales;
                       L_floor_km, n_hill)
    Not used when router is given.

    fixed_params : build the DistFit (Ia per storm, table, router) for these
                   parameters without optimisation; start_log is attached as .starts.

    Default stopping rule (20 / 6 / 3 within 1 %): from a convergence test on a
    synthetic basin and a 12-start Clear Creek log. If 54-75 % of starts reach the
    minimum (synthetic storms) the rule stops after about 6 starts; if about 1 in
    6 does (Clear Creek), all 20 run, giving about 97 % probability of reaching
    it. Stopping after 2 agreeing starts missed the minimum in about 20 % of
    trials on the Clear Creek log.
    """
    router = router or Router(cells, dt, bin_km, hill_exp, L_floor_km, n_hill)
    a_cells = cells.area_mi2.sum()
    if abs(a_cells / gauge_area_mi2 - 1) > 0.05:
        warnings.warn(f"basin cells cover {a_cells:.1f} mi^2 but the gauge area is "
                      f"{gauge_area_mi2:.1f} mi^2 -- check the basin outline")
    use_gw = kb_days is not None and fit_return_flow
    names, lo, hi, x0b, sdb = param_space(a_imp, use_gw, c_bounds, D_bounds, k_hill_bounds,
                                          fc_bounds, a_imp_bounds, beta_bounds, k_gw_bounds)
    if fixed_params is not None:
        best_x = np.clip(_pack(fixed_params, a_imp, use_gw), lo, hi)
        start_log = start_log if start_log is not None else pd.DataFrame()
        return _build_fit(best_x, events, cells, router, gauge_area_mi2, dt, a_imp, d_imp,
                          normalize, kb_days, use_gw, start_log)
    rng = np.random.default_rng(seed)
    starts = start_points(lo, hi, x0b, n_starts, start_design, np.array(sdb), rng)
    resid = lambda x: _dist_resid(x, events, router, gauge_area_mi2, dt, a_imp, d_imp,
                                  normalize, kb_days, use_gw)[0]
    best, rows = None, []
    for s_, x0 in enumerate(starts):
        sol = optimize.least_squares(resid, x0, bounds=(lo, hi), x_scale="jac", max_nfev=max_nfev)
        p_ = _unpack(sol.x, a_imp, d_imp, use_gw)
        rows.append({"start": s_, "from": "default guess" if s_ == 0 else start_design,
                     "SSE": 2 * sol.cost, "c_ms": p_.c_ms, "D_m2s": p_.D_m2s, "k_hill_h": p_.k_hill_h,
                     "fc": p_.fc, "a_imp": p_.a_imp, "beta": p_.beta, "k_gw_h": p_.k_gw_h,
                     "evaluations": sol.nfev, "converged": bool(sol.success)})
        if best is None or sol.cost < best.cost:
            best = sol
        n_hit = sum(r["SSE"] <= 2 * best.cost * (1 + rel_tol) for r in rows)
        if verbose:
            print(f"  start {s_:2d}: SSE {2 * sol.cost:10.4f}   best {2 * best.cost:10.4f}   "
                  f"starts at best: {n_hit}")
        if stop_repeats and s_ + 1 >= min_starts and n_hit >= stop_repeats:
            break
    start_log = pd.DataFrame(rows)
    start_log["SSE_above_best_pct"] = 100 * (start_log.SSE / start_log.SSE.min() - 1)
    return _build_fit(best.x, events, cells, router, gauge_area_mi2, dt, a_imp, d_imp,
                      normalize, kb_days, use_gw, start_log)


def _build_fit(x, events, cells, router, gauge_area_mi2, dt, a_imp, d_imp, normalize,
               kb_days, use_gw, start_log) -> DistFit:
    """DistFit (parameters, per-storm Ia and scores) for the optimizer vector x."""
    _, p, info = _dist_resid(x, events, router, gauge_area_mi2, dt, a_imp, d_imp,
                             normalize, kb_days, use_gw)
    rows = []
    for ev, (ia, st, sim, target, base) in zip(events, info):
        loc = rain_location(ev, cells)
        tm = timing_metrics(target, sim, dt)
        rows.append({"start": ev.time[0], "rain_in": ev.rain_in, "runoff_in": ev.runoff_in,
                     "Ia_in": ia, "status": st, "Q0_cfs": ev.Q0, **loc,
                     "nse_dist": m.nse(target, sim),                 # event flow only
                     "nse_total": m.nse(ev.Q_obs, sim + base),       # whole hydrograph
                     "TE": tm["TE"], "timing_error_h": tm["EMD_h"],
                     "centroid_shift_h": tm["centroid_shift_h"],
                     "peak_obs_cfs": ev.Q_obs.max(), "peak_dist_cfs": (sim + base).max()})
    return DistFit(p, list(events), cells, pd.DataFrame(rows), router, dt, kb_days, start_log)


def recession_pairs(flow: pd.Series, min_days: int = 5, skip_days: int = 3) -> pd.Series:
    """Day-to-day recession constants -1/ln(Q[t+1]/Q[t]) (days) on daily means,
    using only days inside runs of >= min_days falling flow, after skipping the
    first skip_days of each run (still quickflow). Gaps in the record (e.g. the
    winters between Apr-Nov downloads) break runs instead of being bridged."""
    daily = flow.resample("1D").mean()               # gaps stay NaN
    r = daily / daily.shift(1)
    falling = (r < 1) & (r > 0)
    run_id = (~falling).cumsum()
    pos = falling.groupby(run_id).cumsum()           # position within falling run
    length = falling.groupby(run_id).transform("sum")
    use = falling & (length >= min_days) & (pos > skip_days)
    return (-1.0 / np.log(r[use])).rename("k_days")


def estimate_kb_days(flow: pd.Series, min_days: int = 5, skip_days: int = 3) -> float:
    """Baseflow recession constant k_b (days): median of recession_pairs."""
    k = recession_pairs(flow, min_days, skip_days)
    if len(k) == 0:
        raise ValueError("no recession periods found -- lower min_days / skip_days")
    return float(np.median(k))
def storm_at(cells: pd.DataFrame, centre_lonlat, radius_km: float, hyetograph: np.ndarray):
    """Synthetic storm: Gaussian-shaped rain cell, scaled so that its centre
    receives the hyetograph. Returns (T, N) cell rainfall. Used for scenario
    tests with storm position."""
    cx, cy = to_km(*centre_lonlat)
    x, y = to_km(cells.lon.values, cells.lat.values)
    w = np.exp(-((x - cx) ** 2 + (y - cy) ** 2) / (2 * radius_km ** 2))
    return np.outer(np.asarray(hyetograph, float), w)


