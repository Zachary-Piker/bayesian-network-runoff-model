        if ax is None:
            _, ax = plt.subplots(figsize=(10, 4))
        x = ev.time
        layers = [sim.Q_recession, sim.Q_return]
        colors = ["#d9d9d9", "#bf9b6f"]
        labels = ["pre-storm recession", "event return flow"]
        if zones:
            layers += [sim.Q_near, sim.Q_mid, sim.Q_far]
            colors += ["#fc8d62", "#8da0cb", "#66c2a5"]
            labels += ["quick runoff: near third", "quick runoff: middle third", "quick runoff: far third"]
        ax.stackplot(x, *layers, colors=colors, alpha=0.55, labels=labels)
        fm = flow_metrics(ev.Q_obs, sim.Q.values, self.dt)
        tm = timing_metrics(ev.Q_obs, sim.Q.values, self.dt, base=sim.Q_recession.values)
        ax.plot(x, ev.Q_obs, "k", lw=1.4, label="Observed")
        ax.plot(x, sim.Q, color="#1b7837", lw=2.2,
                label=f"Model (NSE {fm['NSE']:.2f}, KGE {fm['KGE']:.2f}, TE {tm['TE']:.2f})")
        if extra is not None:
            ax.plot(x, extra, color="#d95f02", ls="--", lw=1.6,
                    label=f"{extra_label} (NSE {m.nse(ev.Q_obs, extra):.2f})")
