@dataclass
class DistParams:
    c_ms: float               # channel wave celerity (m/s)
    D_m2s: float              # hydrodynamic dispersion (m^2/s)
    k_hill_h: float           # hillslope linear-reservoir residence time (h)
    fc: float                 # pervious constant loss (in/h)
    a_imp: float              # impervious fraction of each cell
    d_imp: float = 0.05       # impervious depression storage (in)
    beta: float = 0.0         # fraction of infiltration returned as event flow
    k_gw_h: float = 72.0      # return-flow reservoir residence time (h)

    def as_dict(self):
        return {"c_m_s": self.c_ms, "D_m2_s": self.D_m2s, "k_hill_h": self.k_hill_h,
                "fc_in_h": self.fc, "a_imp": self.a_imp, "d_imp_in": self.d_imp,
                "beta": self.beta, "k_gw_h": self.k_gw_h}

    def travel_time_h(self, L_km):
        return np.asarray(L_km) * 1000.0 / self.c_ms / 3600.0


def _invgauss_cdf(t, mu, lam):
    """Inverse-Gaussian CDF, vectorised and overflow-safe (log space)."""
    from scipy.special import ndtr, log_ndtr
    t = np.maximum(t, 1e-12)
    r = np.sqrt(lam / t)
    a = ndtr(r * (t / mu - 1.0))
    b = np.exp(2.0 * lam / mu + log_ndtr(-r * (t / mu + 1.0)))
    return np.clip(a + b, 0.0, 1.0)


def channel_kernels(L_km: np.ndarray, c_ms: float, D_m2s: float, dt: float,
                    max_h: float = 300.0) -> np.ndarray:
    """Pulse-response kernels (1/h), one row per channel length, from the exact
    inverse-Gaussian (advection-diffusion first-passage) CDF:
        mean = L/c, shape lambda = L^2 / (2D)."""
    L = np.maximum(np.asarray(L_km, float), 0.0) * 1000.0
    mu = L / c_ms / 3600.0
    lam = np.where(L > 0, L ** 2 / (2 * D_m2s) / 3600.0, 1.0)
    span = np.max(mu + 8 * np.sqrt(mu ** 3 / np.maximum(lam, 1e-9))) + 2
    n = int(min(max_h, span) / dt) + 2
    t = np.arange(n + 1) * dt
    instant = mu < dt / 20
    mu_s, lam_s = np.where(instant, 1.0, mu), np.where(instant, 1.0, lam)
    S = _invgauss_cdf(t[None, :], mu_s[:, None], lam_s[:, None])
    S[:, 0] = 0.0
    K = np.diff(S, axis=1) / dt
    K[instant] = 0.0
    K[instant, 0] = 1.0 / dt                      # negligible channel length: instantaneous
    return K


def hillslope_kernel(k_h: float, dt: float, tol: float = 1e-5) -> np.ndarray:
    n = int(np.ceil(-np.log(tol) * k_h / dt)) + 1
    S = 1 - np.exp(-np.arange(n + 1) * dt / k_h)
    return np.diff(S) / dt


def cell_excess(P: np.ndarray, p: DistParams, Ia: float, dt: float, a_imp=None):
    """Effective rain (in/step, per unit area of each cell). P: (T, N)."""
    a = p.a_imp if a_imp is None else np.asarray(a_imp)
    cum = np.cumsum(P, axis=0)
    imp = np.diff(np.maximum(cum - p.d_imp, 0.0), axis=0, prepend=0.0)
    after = np.minimum(P, np.maximum(cum - Ia, 0.0))
    perv = np.maximum(after - p.fc * dt, 0.0)
    return a * imp + (1 - a) * perv


def hill_scales(cells: pd.DataFrame, hill_exp: float = 1.0, L_floor_km: float = 0.25) -> np.ndarray:
    """Per-cell multiplier s_i on the hillslope residence time, k_i = k_hill * s_i,
    from each cell's 2-D distance to the nearest mapped stream:

        s_i = (max(L_hill_i, L_floor) / Lbar) ** hill_exp,
        Lbar = area-weighted mean of max(L_hill, L_floor) over the basin.

    hill_exp = 0 gives s_i = 1 (uniform k_hill). hill_exp = 1 makes the
    residence time proportional to distance to the stream. L_floor represents
    cells crossed by a stream: for a 1 km cell bisected by a stream, the mean
    distance to the stream is about 0.25 km. With the area-weighted
    normalisation, k_hill is the residence time at the basin-mean distance."""
    if hill_exp == 0:
        return np.ones(len(cells))
    Lh = np.maximum(cells.L_hill_km.values.astype(float), L_floor_km)
    A = cells.area_mi2.values
    Lbar = np.sum(A * Lh) / A.sum()
    return (Lh / Lbar) ** hill_exp


class Router:
    """Precomputes distance bins for a set of cells; routes cell excess -> Q (cfs).

    Cells are grouped into 'columns'. With hill_exp = 0 (default) a column is one
    band of channel distance (bin_km wide), and every cell in it shares the same
    kernel: hillslope reservoir(k_hill) * inverse Gaussian(L_band).

    With hill_exp > 0 each band is further split into n_hill classes of distance
    to the stream (L_hill), and class c gets its own hillslope residence time
    k_hill * s_c (s_c = area-weighted mean of hill_scales over its cells):
        G_column(t) = reservoir(k_hill * s_c) * inverse Gaussian(L_band).
    Attributes used elsewhere keep their meaning per column: L_bins (channel
    distance of the column), bin_idx (column of each cell), B (cell -> column areas)."""
    def __init__(self, cells: pd.DataFrame, dt: float, bin_km: float = 0.5,
                 hill_exp: float = 0.0, L_floor_km: float = 0.25, n_hill: int = 8):
        self.cells, self.dt = cells, dt
        self.hill_exp, self.L_floor_km = float(hill_exp), float(L_floor_km)
        A = cells.area_mi2.values
        band = np.floor(cells.L_channel_km.values / bin_km).astype(int)
        self.cell_scale = hill_scales(cells, hill_exp, L_floor_km)
        if hill_exp == 0 or n_hill <= 1:
            cls = np.zeros(len(cells), int)
        else:                                     # equal-area classes of distance to stream
            o = np.argsort(self.cell_scale, kind="stable")
            cumA = np.cumsum(A[o]) / A.sum()
            cls = np.empty(len(cells), int)
            cls[o] = np.minimum((cumA - 0.5 * A[o] / A.sum()) * n_hill, n_hill - 1).astype(int)
        nc = cls.max() + 1
        self.class_scale = np.array([np.sum(A[cls == c] * self.cell_scale[cls == c]) /
                                     max(np.sum(A[cls == c]), 1e-12) for c in range(nc)])
        pair = band * nc + cls
        cols, self.bin_idx = np.unique(pair, return_inverse=True)
        self.band_of_col, self.class_of_col = cols // nc, cols % nc
        self.L_bins = (self.band_of_col + 0.5) * bin_km
        self.B = np.zeros((len(cells), len(cols)))
        self.B[np.arange(len(cells)), self.bin_idx] = A
        self._cache = {}

    def k_cells(self, p: DistParams) -> np.ndarray:
        """Hillslope residence time (h) of each cell."""
        return p.k_hill_h * self.class_scale[self.class_of_col[self.bin_idx]]

    def kernels(self, p: DistParams):
        key = (round(p.c_ms, 8), round(p.D_m2s, 6), round(p.k_hill_h, 8))
        if key not in self._cache:
            self._cache.clear()
            Kc = channel_kernels(self.L_bins, p.c_ms, p.D_m2s, self.dt)
            hs = [hillslope_kernel(max(p.k_hill_h * s, 1e-3), self.dt) for s in self.class_scale]
            K = np.zeros((len(self.L_bins), Kc.shape[1] + max(len(h) for h in hs) - 1))
            for c, hh in enumerate(hs):
                rows = self.class_of_col == c
                if rows.any():
                    Kr = signal.fftconvolve(Kc[rows], hh[None, :], axes=1) * self.dt
                    K[rows, :Kr.shape[1]] = Kr
            self._cache[key] = K
        return self._cache[key]

    def route(self, pe_cells: np.ndarray, p: DistParams, length: Optional[int] = None,
              by_bin: bool = False):
        K = self.kernels(p)
        W = pe_cells @ self.B                       # (T, nbins) in*mi^2 per step
        T = len(pe_cells) if length is None else length
        Qb = signal.fftconvolve(W, K.T, axes=0)[:T] * m.CFS_PER_INHR_MI2
        if Qb.shape[0] < T:
            Qb = np.pad(Qb, ((0, T - Qb.shape[0]), (0, 0)))
        Qb = np.maximum(Qb, 0.0)
        return Qb if by_bin else Qb.sum(1)


# ---------- baseflow ---------------------------------------------------------
#   Q_base(t) = Q0 * exp(-t / k_b)                       pre-event recession
#             + beta * [infiltration * linear reservoir(k_gw)](t)   event return flow
#   k_b is estimated from recession periods in the flow record (fixed);
#   beta and k_gw are calibrated with the other parameters.

def recession(Q0: float, n: int, dt: float, kb_days: float) -> np.ndarray:
    """Pre-event recession Q0 exp(-t/k_b), with t = 0 at the window start."""
    return Q0 * np.exp(-np.arange(n) * dt / (24.0 * kb_days))


def infiltration(P: np.ndarray, pe: np.ndarray, A: np.ndarray) -> np.ndarray:
    """Infiltration (rainfall minus effective rainfall), basin total per step (in*mi^2)."""
    return (P - pe) @ A


def gw_return_flow(infil: np.ndarray, p: DistParams, dt: float, length: int) -> np.ndarray:
    """Event return flow (cfs): fraction beta of infiltration through a linear reservoir."""
    if p.beta <= 0:
        return np.zeros(length)
    h = m.nash_kernel(1.0, p.k_gw_h, dt)
    q = np.convolve(p.beta * infil, h)[:length] * m.CFS_PER_INHR_MI2
    return np.pad(q, (0, max(0, length - len(q))))


def simulate_distributed(rain_cells: np.ndarray, cells: pd.DataFrame, p: DistParams,
                         Ia: float, dt: float = 0.25, baseflow=0.0, pad_h: float = 72.0,
                         router: Optional[Router] = None, Q0: Optional[float] = None,
                         kb_days: Optional[float] = None) -> pd.DataFrame:
    """Hydrograph for an arbitrary space-time rainfall field.

    rain_cells : (T, N) inches per step for the N basin cells (same order as `cells`).
    Baseflow   : give Q0 (flow just before the storm, cfs) and kb_days to model it as
                 pre-event recession + event return flow (beta, k_gw). Otherwise
                 `baseflow` (constant or array) is added as given.
    Returns t_h, basin-mean rain, excess, Q_direct, Q_recession, Q_return, baseflow,
    Q, and Q from the near / middle / far thirds of the basin."""
    P = np.asarray(rain_cells, float)
    P = np.vstack([P, np.zeros((int(pad_h / dt), P.shape[1]))])
    router = router or Router(cells, dt)
    pe = cell_excess(P, p, Ia, dt)
    Qb = router.route(pe, p, by_bin=True)
    A = cells.area_mi2.values
    n = len(P)
    t = (np.arange(n) + 1) * dt
    q_ret = gw_return_flow(infiltration(P, pe, A), p, dt, n)
    if Q0 is not None and kb_days is not None:
        q_rec = recession(Q0, n, dt, kb_days)
    else:
        bf = np.asarray(baseflow, float)
        q_rec = np.full(n, float(bf)) if bf.ndim == 0 else \
            np.pad(bf, (0, max(0, n - len(bf))), mode="edge")[:n]
    edges = np.quantile(router.L_bins[router.bin_idx], [1 / 3, 2 / 3])
    zone = np.digitize(router.L_bins, edges)
    out = pd.DataFrame({"t_h": t, "rain": P @ A / A.sum(), "excess": pe @ A / A.sum(),
                        "Q_direct": Qb.sum(1), "Q_recession": q_rec, "Q_return": q_ret,
                        "baseflow": q_rec + q_ret, "Q": Qb.sum(1) + q_rec + q_ret})
    for z, name in enumerate(["Q_near", "Q_mid", "Q_far"]):
        out[name] = Qb[:, zone == z].sum(1)
    return out


def geomorphic_iuh(cells: pd.DataFrame, p: DistParams, dt: float = 0.25, hours: float = 96,
                   router=None):
    """GIUH for spatially uniform rainfall (width-function IUH): (t_h, u [1/h])."""
    r = router or Router(cells, dt)
    imp = np.zeros((int(hours / dt), len(cells))); imp[0] = 1.0
    q = r.route(imp, p) / (cells.area_mi2.sum() * m.CFS_PER_INHR_MI2)
    return (np.arange(len(q)) + 1) * dt, q


