FIT_FORMAT = 2          # increment when the model changes; invalidates cached fits


def _fit_key(events, cells, kwargs) -> str:
    """Hash of the fit inputs: storms (times, rainfall and flow totals), radar
    cells and scalar settings."""
    import hashlib
    parts = [f"format={FIT_FORMAT}", f"cells={len(cells)}:{cells.area_mi2.sum():.6f}:"
             f"{cells.L_channel_km.sum():.4f}:{cells.L_hill_km.sum():.4f}"]
    for ev in events:
        parts.append(f"{ev.time[0]}|{len(ev.time)}|{float(np.sum(ev.rain_cells)):.6f}|"
                     f"{float(np.sum(ev.Q_obs)):.4f}")
    for k in sorted(kwargs):
        if k == "verbose":                      # does not affect the result
            continue
        v = kwargs[k]
        if v is None or isinstance(v, (int, float, str, bool, tuple)):
            parts.append(f"{k}={v!r}")
    return hashlib.sha1("\n".join(parts).encode()).hexdigest()[:12]


def fit_saved(events: Sequence[DistEvent], cells: pd.DataFrame, dt: float = 0.25,
              folder: str = "data/fits", label: str = "fit", reuse: bool = True,
              **kwargs) -> DistFit:
    """fit_distributed with on-disk caching. A fit with the same storms, cells and
    settings (including n_starts) is loaded from `folder`; each setting combination
    has its own file. reuse=False forces a refit. The cache stores parameters,
    storm table and start log; storms, cells and router are rebuilt from the
    arguments."""
    import pickle
    os.makedirs(folder, exist_ok=True)
    key = _fit_key(events, cells, {"dt": dt, **kwargs})
    path = os.path.join(folder, f"{label}_{key}.pkl")
    router_args = dict(bin_km=kwargs.get("bin_km", 0.5), hill_exp=kwargs.get("hill_exp", 0.0),
                       L_floor_km=kwargs.get("L_floor_km", 0.25), n_hill=kwargs.get("n_hill", 8))
    if reuse and os.path.exists(path):
        with open(path, "rb") as fh:
            s = pickle.load(fh)
        router = kwargs.get("router") or Router(cells, dt, **router_args)
        n_st = 0 if s["starts"] is None else len(s["starts"])
        print(f"loaded saved fit '{label}' ({n_st} starts) from {path}; set REUSE_FIT = False (reuse=False) to refit")
        return DistFit(s["params"], list(events), cells, s["table"], router, dt, s["kb_days"], s["starts"])
    fit = fit_distributed(events, cells, dt, **kwargs)
    with open(path, "wb") as fh:
        pickle.dump({"params": fit.params, "table": fit.table, "starts": fit.starts,
                     "kb_days": fit.kb_days}, fh)
    print(f"saved fit '{label}' to {path}")
    return fit