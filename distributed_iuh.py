def pick_example_cell(cells: pd.DataFrame, min_cells_from_stream: float = 1.5,
                      quantile: float = 0.75) -> int:
    """Row label of a representative cell for figures: entirely inside the basin,
    at least `min_cells_from_stream` cell widths from the nearest stream, and
    closest to the given quantile of channel distance. Falls back to the cells
    farthest from a stream."""
    full = cells[cells.frac > 0.99]
    full = full if len(full) else cells
    width_km = float(np.sqrt(full.area_mi2.median() * 2.589988))
    cand = full[full.L_hill_km >= min_cells_from_stream * width_km]
    if cand.empty:
        cand = full.nlargest(max(1, len(full) // 10), "L_hill_km")
    target = cells.L_channel_km.quantile(quantile)
    return int((cand.L_channel_km - target).abs().idxmin())


