def _compass(ax, loc: str = "upper right", size: float = 30, color: str = "k"):
    """Compass rose with all four cardinal directions (N arm filled), drawn in
    screen units so it stays square whatever the map's aspect ratio. Map axes are
    longitude (east to the right) and latitude (north up)."""
    from matplotlib.offsetbox import AnchoredOffsetbox, DrawingArea
    from matplotlib.patches import Polygon
    from matplotlib.text import Text
    da = DrawingArea(2 * size, 2 * size, 0, 0)
    c, r, w = size, 0.58 * size, 0.14 * size
    for ang, label in ((90, "N"), (0, "E"), (270, "S"), (180, "W")):
        th = np.radians(ang)
        ux, uy, px, py = np.cos(th), np.sin(th), -np.sin(th), np.cos(th)
        tip = (c + r * ux, c + r * uy)
        for side, fill in ((1, color), (-1, "w")):        # two-tone arm: dark and light halves
            fc = color if label == "N" else fill
            da.add_artist(Polygon([tip, (c, c), (c + side * w * px, c + side * w * py)], closed=True,
                                  fc=fc, ec=color, lw=0.8))
        rl = r + 0.27 * size
        da.add_artist(Text(c + rl * ux, c + rl * uy, label, ha="center", va="center",
                           fontsize=max(6.5, size / 3.6), fontweight="bold", color=color))
    box = AnchoredOffsetbox(loc=loc, child=da, pad=0.1, borderpad=0.4, frameon=True)
    box.patch.set(facecolor="w", alpha=0.75, edgecolor="none")
    ax.add_artist(box)
    return box


def _scale_bar(ax, km=5.0, loc=(0.05, 0.06), color="k", compass: bool = True,
               compass_size: float = 30, compass_loc: str = "upper right"):
    """Scale bar (km) and, by default, a compass rose at compass_loc. loc is the
    left end of the bar in axes fractions, or "lower left" / "lower right"."""
    x0, x1 = ax.get_xlim(); y0, y1 = ax.get_ylim()
    lat = (y0 + y1) / 2
    dlon = km / (111.320 * np.cos(np.radians(lat)))
    if loc == "lower right":
        bx, by = x1 - 0.05 * (x1 - x0) - dlon, y0 + 0.06 * (y1 - y0)
    else:
        if loc == "lower left":
            loc = (0.05, 0.06)
        bx, by = x0 + loc[0] * (x1 - x0), y0 + loc[1] * (y1 - y0)
    ax.plot([bx, bx + dlon], [by, by], color=color, lw=3, solid_capstyle="butt")
    ax.text(bx + dlon / 2, by + 0.012 * (y1 - y0), f"{km:g} km", ha="center", va="bottom",
            fontsize=8, color=color)
    if compass:
        _compass(ax, compass_loc, compass_size, color)


