        if logy:
            ax.set_yscale("log")
            ax.set_ylim(max(min(ev.Q_obs.min(), sim.Q_recession.min()) * 0.7, 1e-2),
                        max(ev.Q_obs.max(), sim.Q.max()) * 1.5)
        else:
            ax.set_ylim(0, max(ev.Q_obs.max(), sim.Q.max()) * 1.15)
        ax2 = ax.twinx()
        A = self.cells.area_mi2.values
