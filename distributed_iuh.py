@dataclass
class DistEvent:
    """One storm: cell rainfall on the model time grid and the observed
    hydrograph components (from a nash_iuh.EventFit on the same window)."""
    time: pd.DatetimeIndex
    rain_cells: np.ndarray        # (T, N) in/step
    Q_obs: np.ndarray
    baseflow: np.ndarray
    Q_direct_obs: np.ndarray
    runoff_in: float              # over the gauge drainage area

    @property
    def rain_in(self):
        return float(np.nanmean(self.rain_cells.sum(0)))

    @property
    def Q0(self) -> float:
        """Pre-event flow (cfs) at the window start: the lowest flow before the first rain."""
        return self.q0()

    def q0(self, kb_days: Optional[float] = None) -> float:
        """Pre-event flow at the window start. With kb_days, each pre-rain sample is
        projected back to t = 0 along the recession before taking the minimum, so
        the recession Q0 exp(-t/k_b) passes through the pre-rain flows."""
        wet = np.where(self.rain_cells.max(1) > 0)[0]
        k = int(wet[0]) + 1 if len(wet) else 1
        q = np.asarray(self.Q_obs[:k], float)
        if kb_days:
            dt = (self.time[1] - self.time[0]) / pd.Timedelta(hours=1)
            q = q * np.exp(np.arange(k) * dt / (24.0 * kb_days))
        return float(np.min(q))


def make_dist_events(fits: Sequence, cell_rain_hourly: pd.DataFrame, dt_min: int = 15) -> list:
    """Pair EventFit objects (flow side) with that window's cell rain, converted
    from hour-ending radar totals to the model time step. Hours missing from the
    radar cache are treated as dry (see radar_coverage)."""
    out = []
    for f in fits:
        P = hourly_to_steps(cell_rain_hourly, pd.DatetimeIndex(f.time), dt_min)
        out.append(DistEvent(pd.DatetimeIndex(f.time), np.nan_to_num(P.values), f.Q_obs,
                             f.baseflow, f.Q_direct_obs, f.runoff_in))
    return out


def radar_coverage(cube: RadarCube, start, end) -> float:
    """Fraction of the hours in [start, end] present (and not all-NaN) in the cache."""
    need = pd.date_range(pd.Timestamp(start).ceil("h"), pd.Timestamp(end).ceil("h"), freq="1h")
    have = cube.times[~np.all(np.isnan(cube.grids.reshape(len(cube.times), -1)), axis=1)]
    return float(np.isin(need, have).mean()) if len(need) else 0.0


def rain_location(ev: DistEvent, cells: pd.DataFrame) -> dict:
    """Rainfall-weighted mean channel distance (km) and the fraction of rainfall
    volume in the near third of the basin."""
    vol = ev.rain_cells.sum(0) * cells.area_mi2.values
    L = cells.L_channel_km.values
    near = L <= np.quantile(L, 1 / 3)
    return {"rain_centroid_km": float(np.sum(vol * L) / max(vol.sum(), 1e-12)),
            "near_third_share": float(vol[near].sum() / max(vol.sum(), 1e-12))}


def solve_ia_dist(ev: DistEvent, p: DistParams, router: Router, gauge_area_mi2: float,
                  dt: float, kb_days: Optional[float] = None):
    """Event initial abstraction Ia so modelled volume == observed volume.

    kb_days None : target = separated direct runoff (straight-line baseflow).
    kb_days set  : target = observed flow minus the pre-event recession, i.e.
                   quick runoff + event return flow (no separation needed). The
                   return-flow volume counted is the part released inside the window.
    """
    A = router.cells.area_mi2.values
    rows = np.where(ev.rain_cells.max(1) > 0)[0]     # dry steps add nothing (exact)
    if len(rows) == 0:
        return 0.0, "no_rain"
    P = ev.rain_cells[rows]
    ptot = float(P.sum(0).max())
    if kb_days is None:
        target = ev.runoff_in * gauge_area_mi2       # in*mi^2
        vol = lambda ia: float((cell_excess(P, p, ia, dt) @ A).sum()) - target
    else:
        n = len(ev.Q_obs)
        rec = recession(ev.q0(kb_days), n, dt, kb_days)
        target = float(np.sum(ev.Q_obs - rec)) * dt / m.CFS_PER_INHR_MI2
        released = 1.0 - np.exp(-(n - rows) * dt / p.k_gw_h) if p.beta > 0 else 0.0  # exact for the discrete kernel
        def vol(ia):
            pe = cell_excess(P, p, ia, dt)
            v = float((pe @ A).sum())
            if p.beta > 0:
                v += p.beta * float(np.sum(infiltration(P, pe, A) * released))
            return v - target
    if target <= 0:
        return ptot, "no_runoff"
    if vol(ptot) >= 0:
        return ptot, "imp_too_big"
    if vol(0.0) <= 0:
        return 0.0, "losses_too_high"
    return optimize.brentq(vol, 0.0, ptot, xtol=1e-6), "ok"


@dataclass
class DistFit:
    params: DistParams
    events: list
    cells: pd.DataFrame
    table: pd.DataFrame
    router: Router
    dt: float
    kb_days: Optional[float] = None      # None = separated baseflow mode
    starts: Optional[pd.DataFrame] = None   # one row per optimizer start (see fit_distributed)

    def simulate_event(self, i: int) -> pd.DataFrame:
        """Columns: Q_direct, Q_near/mid/far, Q_recession, Q_return, baseflow, Q."""
        ev, p = self.events[i], self.params
        P, n = ev.rain_cells, len(ev.Q_obs)
        pe = cell_excess(P, p, self.table.Ia_in.iloc[i], self.dt)
        Qb = self.router.route(pe, p, length=n, by_bin=True)
        edges = np.quantile(self.router.L_bins[self.router.bin_idx], [1 / 3, 2 / 3])
        zone = np.digitize(self.router.L_bins, edges)
        df = pd.DataFrame({"Q_direct": Qb.sum(1)}, index=ev.time)
        for z, name in enumerate(["Q_near", "Q_mid", "Q_far"]):
            df[name] = Qb[:, zone == z].sum(1)
        if self.kb_days is None:
            df["Q_recession"], df["Q_return"] = ev.baseflow, 0.0
        else:
            df["Q_recession"] = recession(ev.q0(self.kb_days), n, self.dt, self.kb_days)
            df["Q_return"] = gw_return_flow(infiltration(P, pe, self.cells.area_mi2.values),
                                            p, self.dt, n)
        df["baseflow"] = df.Q_recession + df.Q_return
        df["Q"] = df.Q_direct + df.baseflow
        return df

    def plot_event(self, i: int, ax=None, zones: bool = False, logy: bool = False,
                   extra: Optional[np.ndarray] = None, extra_label: str = "other model"):
        """Observed vs modelled total flow for storm i, with basin-mean rain bars.

        Shaded layers: pre-storm recession and event return flow (the modelled
        baseflow). zones=True also stacks the quick runoff from the near,
        middle and far thirds of the basin. The legend carries NSE, KGE and
        the timing efficiency TE (see timing_metrics). `extra` adds another
        total-flow series (e.g. a different model) as a dashed line."""
