def set_origin(lon: float, lat: float):
    """Set the projection origin (called by build_channel_network with the outlet)."""
    _ORIGIN["lon"], _ORIGIN["lat"] = float(lon), float(lat)


def to_km(lon, lat, lat0: Optional[float] = None, lon0: Optional[float] = None):
    """Local equirectangular projection (km): x = R cos(lat0) (lon - lon0),
    y = R (lat - lat0), angles in radians. Error < 0.5 % within ~50 km of the
    origin, which is set to the basin outlet."""
    lat0 = _ORIGIN["lat"] if lat0 is None else lat0
    lon0 = _ORIGIN["lon"] if lon0 is None else lon0
    lon, lat = np.asarray(lon, float), np.asarray(lat, float)
    return ((lon - lon0) * 111.320 * np.cos(np.radians(lat0)),
            (lat - lat0) * 110.574)


def _nldi_get(path: str, params=None):
    import requests
    last = None
    for base in NLDI_BASES:
        try:
            r = requests.get(f"{base}{path}", params=params, timeout=120)
            if r.ok:
                return r.json()
            last = f"{r.status_code} {r.text[:200]}"
        except Exception as e:      # try the next base URL
            last = str(e)
    raise RuntimeError(f"NLDI request failed for {path}: {last}")


def fetch_nldi_geometry(site: str = "05454300", out_dir: str = "data",
                        nav_distance_km: int = 1000) -> dict:
    """Download (and save as GeoJSON) the gauge point, its upstream basin, and
    all upstream flowlines (NHDPlus) from the USGS NLDI service."""
    os.makedirs(out_dir, exist_ok=True)
    fid = f"/linked-data/nwissite/USGS-{site}"
    out = {"site": _nldi_get(fid, {"f": "json"}),
           "basin": _nldi_get(f"{fid}/basin", {"f": "json"}),
           "flowlines": _nldi_get(f"{fid}/navigation/UT/flowlines",
                                  {"distance": nav_distance_km, "f": "json"})}
    import json
    for k, v in out.items():
        with open(os.path.join(out_dir, f"nldi_{k}.geojson"), "w") as fh:
            json.dump(v, fh)
    return out


def polygon_area_mi2(ring: np.ndarray) -> float:
    """Area (mi^2) of a lon/lat polygon: project to km, then the shoelace formula
    A = 0.5 |sum(x_k y_{k+1} - x_{k+1} y_k)|."""
    x, y = to_km(ring[:, 0], ring[:, 1], lat0=float(np.mean(ring[:, 1])),
                 lon0=float(np.mean(ring[:, 0])))
    return float(0.5 * abs(np.dot(x, np.roll(y, -1)) - np.dot(np.roll(x, -1), y)) / KM2_PER_MI2)


def fetch_site_info(site: str, out_dir: str) -> dict:
    """Name, location and published drainage area of a USGS gauge (cached as
    site_info.json). Uses the USGS Water Data API (monitoring-locations), and
    falls back to the NLDI site record for name and coordinates."""
    import json
    import requests
    path = os.path.join(out_dir, "site_info.json")
    if os.path.exists(path):
        with open(path) as fh:
            return json.load(fh)
    os.makedirs(out_dir, exist_ok=True)
    info = {"site": site}
    for ver in ("v1", "v0"):
        try:
            r = requests.get(f"https://api.waterdata.usgs.gov/ogcapi/{ver}/collections/"
                             f"monitoring-locations/items/USGS-{site}", params={"f": "json"}, timeout=60)
            if not r.ok:
                continue
            js = r.json(); pr = js.get("properties", {})
            lon, lat = js["geometry"]["coordinates"][:2]
            info.update(name=pr.get("monitoring_location_name"), lon=lon, lat=lat,
                        state=pr.get("state_name"), huc=pr.get("hydrologic_unit_code"),
                        drainage_area_mi2=pr.get("drainage_area"),
                        contributing_area_mi2=pr.get("contributing_drainage_area"),
                        source=f"USGS Water Data API {ver}")
            break
        except Exception:
            pass
    if "lon" not in info:                          # fallback: NLDI
        g = _nldi_get(f"/linked-data/nwissite/USGS-{site}", {"f": "json"})
        f0 = g["features"][0]
        info.update(name=f0["properties"].get("name"), lon=f0["geometry"]["coordinates"][0],
                    lat=f0["geometry"]["coordinates"][1], drainage_area_mi2=None, source="NLDI")
    with open(path, "w") as fh:
        json.dump(info, fh, indent=1)
    return info


def load_or_fetch_flow(site: str, years, path: str, download: bool = True) -> pd.Series:
    """15-minute discharge (cfs, UTC) for whole calendar years, cached as CSV
    (columns time, value). Years in `years` that are absent from the cache are
    downloaded (one request per year) and appended. download=False uses the
    cache only. Returns the record for `years`."""
    years = list(years)
    cached = m.load_usgs_csv(path) if os.path.exists(path) else None
    have = set(cached.index.year) if cached is not None else set()
    todo = [y for y in years if y not in have]
    if todo and not download:
        print(f"  flow: years {todo} not in the cache and not downloaded")
        todo = []
    parts = [cached] if cached is not None else []
    for y in todo:
        try:
            parts.append(m.fetch_usgs_iv(site, f"{y}-01-01", f"{y + 1}-01-01"))
            print(f"  {y}: {len(parts[-1]):,} values")
        except Exception as e:
            print(f"  {y}: no data ({e})")
    if not parts:
        raise RuntimeError("no 15-minute discharge found for these years")
    q = pd.concat(parts).sort_index()
    q = q[~q.index.duplicated()]
    if todo:
        os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
        q.to_csv(path, index_label="time", header=["value"])
    q = q[q.index.year.isin(years)]
    if q.empty:
        raise RuntimeError("no cached 15-minute discharge for these years")
    return q


def _geoms(gj):
    if isinstance(gj, str):
        import json
        with open(gj) as fh:
            gj = json.load(fh)
    if gj.get("type") == "FeatureCollection":
        return [f["geometry"] for f in gj["features"] if f.get("geometry")]
    if gj.get("type") == "Feature":
        return [gj["geometry"]]
    return [gj]


def load_lines(geojson) -> list:
    """List of (n, 2) lon/lat arrays from a (Multi)LineString GeoJSON."""
    lines = []
    for g in _geoms(geojson):
        if g["type"] == "LineString":
            lines.append(np.asarray(g["coordinates"], float)[:, :2])
        elif g["type"] == "MultiLineString":
            lines += [np.asarray(c, float)[:, :2] for c in g["coordinates"]]
    return lines


def load_ring(geojson) -> np.ndarray:
    """Largest outer ring (lon, lat) of a (Multi)Polygon GeoJSON."""
    rings = []
    for g in _geoms(geojson):
        if g["type"] == "Polygon":
            rings.append(np.asarray(g["coordinates"][0], float)[:, :2])
        elif g["type"] == "MultiPolygon":
            rings += [np.asarray(p[0], float)[:, :2] for p in g["coordinates"]]
    return max(rings, key=len)


def load_point(geojson):
    g = _geoms(geojson)[0]
    return tuple(np.asarray(g["coordinates"], float)[:2])


@dataclass
class ChannelNetwork:
    lonlat: np.ndarray        # (n, 2) vertices
    xy: np.ndarray            # (n, 2) km
    dist_km: np.ndarray       # along-channel distance to outlet (inf = unreachable)
    outlet_snap_km: float
    pred: Optional[np.ndarray] = None   # next vertex toward the outlet (-9999 at outlet)

    @property
    def reachable(self):
        return np.isfinite(self.dist_km)


def build_channel_network(lines: Sequence[np.ndarray], outlet_lonlat,
                          snap_m: float = 60.0) -> ChannelNetwork:
    """Graph of flowline vertices; along-channel distance from every vertex to
    the vertex nearest the outlet (Dijkstra). Endpoints closer than snap_m are
    joined to bridge digitising gaps."""
    set_origin(*outlet_lonlat)                # projection origin at the outlet
    keys, verts, rows, cols, w = {}, [], [], [], []
    def vid(pt):
        k = (round(pt[0], 7), round(pt[1], 7))
        if k not in keys:
            keys[k] = len(verts); verts.append(pt)
        return keys[k]
    ends = []
    for ln in lines:
        ids = [vid(p) for p in ln]
        ends += [ids[0], ids[-1]]
        for a, b in zip(ids[:-1], ids[1:]):
            if a != b:
                rows.append(a); cols.append(b)
    lonlat = np.asarray(verts)
    xy = np.column_stack(to_km(lonlat[:, 0], lonlat[:, 1]))
    tree = cKDTree(xy)
    for e in set(ends):                       # bridge small gaps at endpoints
        for nb in tree.query_ball_point(xy[e], snap_m / 1000.0):
            if nb != e:
                rows.append(e); cols.append(nb)
    rows, cols = np.array(rows), np.array(cols)
    w = np.linalg.norm(xy[rows] - xy[cols], axis=1) + 1e-9
    G = coo_matrix((w, (rows, cols)), shape=(len(xy),) * 2).tocsr()
    ox, oy = to_km(*outlet_lonlat)
    snap, outlet = tree.query([float(ox), float(oy)])
    d, pred = dijkstra(G, directed=False, indices=outlet, return_predecessors=True)
    if snap > 0.5:
        warnings.warn(f"outlet is {snap:.2f} km from the nearest flowline vertex -- "
                      "check the gauge coordinates")
    return ChannelNetwork(lonlat, xy, d, float(snap), pred)


def basin_cells(lon1d, lat1d, ring: np.ndarray, net: ChannelNetwork,
                sub: int = 6) -> pd.DataFrame:
    """Radar cells overlapping the basin, with the fraction of each cell inside
    the basin, its area (mi^2), and its flow distances:
        L_channel_km : along-channel distance from the nearest channel vertex to the outlet
        L_hill_km    : straight-line distance from cell centre to that channel vertex
    """
    from matplotlib.path import Path
    lon1d, lat1d = np.asarray(lon1d), np.asarray(lat1d)
    dlon, dlat = abs(np.median(np.diff(lon1d))), abs(np.median(np.diff(lat1d)))
    path = Path(ring)
    bx0, by0 = ring.min(0) - [dlon, dlat]
    bx1, by1 = ring.max(0) + [dlon, dlat]
    ix = np.where((lon1d >= bx0) & (lon1d <= bx1))[0]
    iy = np.where((lat1d >= by0) & (lat1d <= by1))[0]
    off = (np.arange(sub) + 0.5) / sub - 0.5
    ox, oy = np.meshgrid(off * dlon, off * dlat)
    rows = []
    for j in iy:
        for i in ix:
            pts = np.column_stack([lon1d[i] + ox.ravel(), lat1d[j] + oy.ravel()])
            frac = path.contains_points(pts).mean()
            if frac > 0:
                a_km2 = frac * dlon * 111.320 * np.cos(np.radians(lat1d[j])) * dlat * 110.574
                rows.append((j, i, lon1d[i], lat1d[j], frac, a_km2 / KM2_PER_MI2))
    cells = pd.DataFrame(rows, columns=["iy", "ix", "lon", "lat", "frac", "area_mi2"])
    r = net.reachable
    tree = cKDTree(net.xy[r])
    cxy = np.column_stack(to_km(cells.lon, cells.lat))
    dh, k = tree.query(cxy)
    cells["L_hill_km"] = dh
    cells["L_channel_km"] = net.dist_km[r][k]
    cells["v_idx"] = np.where(r)[0][k]          # channel vertex each cell drains to
    return cells


def channel_path(net: ChannelNetwork, v: int) -> np.ndarray:
    """(n, 2) lon/lat of the channel path from vertex v down to the outlet."""
    if net.pred is None:
        raise ValueError("rebuild the network with build_channel_network (needs predecessors)")
    path = [v]
    while net.pred[path[-1]] >= 0 and len(path) < 100000:
        path.append(int(net.pred[path[-1]]))
    return net.lonlat[path]


def plot_distance_histogram(cells: pd.DataFrame, bins: int = 12, weight: str = "area", ax=None):
    """Histogram of channel distance to the outlet (km) over the basin's radar cells.

    weight="area"  : bar height = basin area in each distance band (mi^2), i.e. the
                     width function in `bins` bins (partial edge cells count by area);
    weight="count" : bar height = number of radar cells.
    Returns (ax, table) where table lists each bin's edges and value."""
    import matplotlib.pyplot as plt
    if ax is None:
        _, ax = plt.subplots(figsize=(7, 3.8))
    L = cells.L_channel_km.values
    w = cells.area_mi2.values if weight == "area" else None
    vals, edges, _ = ax.hist(L, bins=bins, weights=w, color="#6c8ebf", edgecolor="k", lw=0.6)
    ax.set_xlabel("Channel distance to outlet (km)")
    ax.set_ylabel("Basin area (mi$^2$)" if weight == "area" else "Number of radar cells")
    ax.set_title(f"Channel distance to the outlet ({bins} bins, {len(cells)} cells, "
                 f"mean {np.average(L, weights=cells.area_mi2):.1f} km, max {L.max():.1f} km)")
    table = pd.DataFrame({"from_km": edges[:-1], "to_km": edges[1:],
                          ("area_mi2" if weight == "area" else "cells"): vals})
    return ax, table


def width_function(cells: pd.DataFrame, bin_km: float = 1.0) -> pd.Series:
    """Basin area (mi^2) per band of channel distance to the outlet."""
    b = np.floor(cells.L_channel_km / bin_km) * bin_km
    return cells.groupby(b).area_mi2.sum().rename("area_mi2")


