AWS_BUCKET = "https://noaa-mrms-pds.s3.amazonaws.com"
IEM_ARCHIVE = "https://mtarchive.geol.iastate.edu"
AWS_START = pd.Timestamp("2020-10-15")


def default_product(t: pd.Timestamp) -> str:
    """Gauge-corrected hourly QPE: 'GaugeCorr_QPE_01H' before the Oct-2020
    MRMS v12 upgrade, 'MultiSensor_QPE_01H_Pass2' after."""
    return "MultiSensor_QPE_01H_Pass2" if t >= AWS_START else "GaugeCorr_QPE_01H"


def day_listing(day: pd.Timestamp, source: str, product: str) -> dict:
    """{valid_time: url} for one UTC day of hourly MRMS files."""
    import requests
    ymd = day.strftime("%Y%m%d")
    if source == "aws":
        url = f"{AWS_BUCKET}/?list-type=2&prefix=CONUS/{product}_00.00/{ymd}/"
        txt = requests.get(url, timeout=60).text
        names = [f"{AWS_BUCKET}/{k}" for k in re.findall(r"<Key>([^<]+)</Key>", txt)]
    else:
        d = f"{IEM_ARCHIVE}/{day:%Y/%m/%d}/mrms/ncep/{product}/"
        r = requests.get(d, timeout=60)
        if not r.ok:
            return {}
        names = [d + h for h in re.findall(r'href="([^"]+\.grib2(?:\.gz)?)"', r.text)]
    out = {}
    for u in names:
        mt = re.search(r"(\d{8})-(\d{6})", u)
        if mt:
            out[pd.Timestamp(f"{mt.group(1)} {mt.group(2)}")] = u
    return out


def read_mrms_grib(path_or_bytes, bbox) -> tuple:
    """Read one MRMS GRIB2(.gz) file and subset to bbox=(lon0, lat0, lon1, lat1).
    Needs xarray + cfgrib (conda install -c conda-forge cfgrib).
    Returns lon1d (ascending, -180..180), lat1d (ascending), grid (ny, nx) in mm,
    with missing (<0) set to NaN."""
    import xarray as xr
    raw = path_or_bytes if isinstance(path_or_bytes, (bytes, bytearray)) else \
        open(path_or_bytes, "rb").read()
    if raw[:2] == b"\x1f\x8b":
        raw = gzip.decompress(raw)
    with tempfile.TemporaryDirectory() as td:
        fn = os.path.join(td, "f.grib2")
        with open(fn, "wb") as fh:
            fh.write(raw)
        ds = xr.open_dataset(fn, engine="cfgrib", decode_timedelta=False,
                             backend_kwargs={"indexpath": ""})
        da = ds[list(ds.data_vars)[0]]
        lon = da.longitude.values
        lon = np.where(lon > 180, lon - 360, lon)
        lat = da.latitude.values
        ix = np.where((lon >= bbox[0]) & (lon <= bbox[2]))[0]
        iy = np.where((lat >= bbox[1]) & (lat <= bbox[3]))[0]
        g = da.values[np.ix_(iy, ix)].astype("float32")
        ds.close()
    lat_s, lon_s = lat[iy], lon[ix]
    oy, ox = np.argsort(lat_s), np.argsort(lon_s)
    g = g[np.ix_(oy, ox)]
    g[g < 0] = np.nan
    return lon_s[ox], lat_s[oy], g


@dataclass
class RadarCube:
    """Hourly radar rainfall over the basin bounding box. grids[t] is the depth
    (in) for the hour ending at times[t] (MRMS convention)."""
    times: pd.DatetimeIndex
    lon1d: np.ndarray
    lat1d: np.ndarray
    grids: np.ndarray            # (T, ny, nx) inches, NaN = missing

    def save(self, path):
        np.savez_compressed(path, times=self.times.values.astype("datetime64[s]"),
                            lon1d=self.lon1d, lat1d=self.lat1d, grids=self.grids)

    @classmethod
    def load(cls, path):
        z = np.load(path)
        return cls(pd.DatetimeIndex(z["times"]), z["lon1d"], z["lat1d"], z["grids"])

    def cell_rain(self, cells: pd.DataFrame) -> pd.DataFrame:
        """Hourly rain (in) per basin cell: DataFrame (time x cell)."""
        v = self.grids[:, cells.iy.values, cells.ix.values]
        return pd.DataFrame(v, index=self.times)

    def basin_average(self, cells: pd.DataFrame) -> pd.Series:
        cr = self.cell_rain(cells)
        w = cells.area_mi2.values
        ok = np.isfinite(cr.values)
        avg = np.nansum(cr.values * w, axis=1) / np.maximum((ok * w).sum(1), 1e-9)
        avg[~ok.any(1)] = np.nan
        return pd.Series(avg, index=self.times, name="rain_in")


def download_radar(hours: Sequence[pd.Timestamp], bbox, cache_path: str = "data/mrms_basin.npz",
                   source: str = "auto", product: Optional[str] = None,
                   verbose: bool = True) -> RadarCube:
    """Download hourly MRMS QPE for the given (hour-ending, UTC) times, keep only
    the basin box, and cache the result (resumable: re-running skips hours
    already in the cache). Full CONUS files are never written to disk.

    source : 'aws' (NOAA Open Data, Oct 2020 onward), 'iem' (Iowa State
             mtarchive, Oct 2014 onward) or 'auto' (aws when available).
    """
    import requests
    hours = pd.DatetimeIndex(sorted(set(pd.DatetimeIndex(hours).floor("h"))))
    cube = RadarCube.load(cache_path) if os.path.exists(cache_path) else None
    have = set(cube.times) if cube is not None else set()
    todo = [h for h in hours if h not in have]
    if verbose:
        print(f"{len(hours)} hours requested, {len(todo)} to download")
    listings, new_t, new_g = {}, [], []
    lon1d, lat1d = (cube.lon1d, cube.lat1d) if cube is not None else (None, None)
    for n, h in enumerate(todo):
        src = source if source != "auto" else ("aws" if h >= AWS_START else "iem")
        prod = product or default_product(h)
        day = h.normalize()
        key = (day, src, prod)
        if key not in listings:
            listings[key] = day_listing(day, src, prod)
        url = listings[key].get(h)
        if url is None:
            if verbose:
                print(f"  missing: {h} ({src}/{prod})")
            continue
        r = requests.get(url, timeout=120)
        r.raise_for_status()
        lo, la, g = read_mrms_grib(r.content, bbox)
        if lon1d is None:
            lon1d, lat1d = lo, la
        new_t.append(h); new_g.append(g / 25.4)          # mm -> in
        if verbose and (n + 1) % 25 == 0:
            print(f"  {n + 1}/{len(todo)}")
        if (n + 1) % 100 == 0 or n == len(todo) - 1:      # checkpoint
            cube = _merge(cube, new_t, new_g, lon1d, lat1d); new_t, new_g = [], []
            cube.save(cache_path)
    if new_t:
        cube = _merge(cube, new_t, new_g, lon1d, lat1d); cube.save(cache_path)
    return cube


def _merge(cube, t, g, lon1d, lat1d):
    if not t:
        return cube
    T, G = pd.DatetimeIndex(t), np.stack(g)
    if cube is not None:
        T = cube.times.append(T); G = np.concatenate([cube.grids, G])
    o = np.argsort(T.values)
    return RadarCube(T[o], lon1d, lat1d, G[o])


def radar_from_folder(folder: str, bbox) -> RadarCube:
    """RadarCube from manually downloaded MRMS files (file names containing
    YYYYMMDD-HHMMSS)."""
    t, g, lo, la = [], [], None, None
    for fn in sorted(os.listdir(folder)):
        mt = re.search(r"(\d{8})-(\d{6})", fn)
        if not mt or ".grib2" not in fn:
            continue
        lo, la, grid = read_mrms_grib(os.path.join(folder, fn), bbox)
        t.append(pd.Timestamp(f"{mt.group(1)} {mt.group(2)}")); g.append(grid / 25.4)
    return _merge(None, t, g, lo, la)


def event_hours(windows: pd.DataFrame, lead_h: float = 12.0) -> pd.DatetimeIndex:
    """Hour-ending times needed to cover each event window (start - lead .. end)."""
    hrs = []
    for _, w in windows.iterrows():
        hrs.append(pd.date_range((w.start - pd.Timedelta(hours=lead_h)).floor("h"),
                                 w.end.ceil("h"), freq="1h"))
    return pd.DatetimeIndex(sorted(set(np.concatenate([h.values for h in hrs]))))


def hourly_to_steps(df_hourly, grid_index: pd.DatetimeIndex, dt_min: int = 15):
    """Spread hour-ending totals evenly over the sub-hourly steps of that hour."""
    per = 60 // dt_min
    lbl = pd.DatetimeIndex(grid_index).ceil("h")
    vals = df_hourly.reindex(lbl).values / per
    out = pd.DataFrame(vals, index=grid_index) if np.ndim(vals) == 2 else \
        pd.Series(vals, index=grid_index)
    return out


