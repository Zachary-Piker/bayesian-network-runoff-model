"""
FUNCTIONS GENERATED BY CLAUDE OPUS 5.5

========================================================================================================
distributed_iuh.py -- distributed (space-time) geomorphic Green's-function for the rainfall-runoff model
========================================================================================================

The effective rainfall on each radar cell is routed to the gauge with a
cell-specific Green's function determined by the cell's channel distance to the
outlet along the mapped stream network:

    Q_d(t) = 645.33 * sum_i  A_i * (p_e,i * G_i)(t)

    G_i = hillslope linear reservoir (k_hill)  *  channel advection-diffusion
          kernel over the cell's channel distance L_i (inverse Gaussian,
          celerity c, diffusivity D):

          g_c(t; L) = L / sqrt(4 pi D t^3) * exp(-(L - c t)^2 / (4 D t))

Cells are grouped in 0.5 km channel-distance bands that share one kernel. For
a spatially uniform rainfall the model reduces to the width-function GIUH.

Losses per cell: impervious fraction a (runoff after depression storage
d = 0.05 in); pervious fraction 1 - a (initial abstraction Ia per storm, then a
constant loss rate fc). In fit_distributed, Ia is set by volume matching; in
sequential_bayes it is estimated in the Bayesian update.

Baseflow: pre-storm recession Q0 exp(-t / k_b), with k_b from recession periods,
plus event return flow beta * (infiltration * linear reservoir k_gw).

Sections
    1. Geometry: gauge record, NLDI basin and streams, projection, stream graph,
       radar cells, width function
    2. MRMS radar rainfall: download, subset, cache
    3. The model: kernels, losses, router, baseflow, simulation, GIUH
    4. Events, least-squares calibration (multi-start) and diagnostics
    5. Maps and figures (3DEP elevation is used for the topographic map only)
    6. Performance metrics: NSE, KGE, timing efficiency, rainfall-peak lags,
       falling-limb check
    7. Cached fits (fit_saved)

Sequential Bayesian calibration of parameters is in sequential_bayes.py.

Units: rain in inches per step, area mi^2, flow cfs, time hours, distances km,
c in m/s, D in m^2/s. All times UTC.
"""

