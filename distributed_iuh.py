def flow_metrics(obs, sim, dt: float = 0.25) -> dict:
    """Standard fit statistics for one storm (both series in cfs, same grid).
        NSE            Nash-Sutcliffe efficiency (1 = perfect, 0 = no better than the mean)
        KGE            Kling-Gupta efficiency  1 - sqrt((r-1)^2 + (a-1)^2 + (b-1)^2),
                       a = std ratio (sim/obs), b = mean ratio (sim/obs)
        r              correlation
        peak_err_pct   100 (peak_sim / peak_obs - 1)
        peak_timing_h  time of simulated peak minus observed peak (+ = model late)
        vol_err_pct    100 (volume_sim / volume_obs - 1)
        RMSE_cfs"""
    o, s_ = np.asarray(obs, float), np.asarray(sim, float)
    r = float(np.corrcoef(o, s_)[0, 1]) if o.std() > 0 and s_.std() > 0 else np.nan
    kge = 1 - np.sqrt((r - 1) ** 2 + (s_.std() / o.std() - 1) ** 2 + (s_.mean() / o.mean() - 1) ** 2)
    return {"NSE": m.nse(o, s_), "KGE": float(kge), "r": r,
            "peak_err_pct": 100 * (s_.max() / o.max() - 1),
            "peak_timing_h": (int(np.argmax(s_)) - int(np.argmax(o))) * dt,
            "vol_err_pct": 100 * (s_.sum() / o.sum() - 1),
            "RMSE_cfs": float(np.sqrt(np.mean((s_ - o) ** 2)))}


def timing_metrics(obs, sim, dt: float = 0.25, base=None, max_shift_h: float = 24.0,
                   tail_frac: Optional[float] = 0.1) -> dict:
    """Timing skill of the simulated response, independent of volume.

    Both hydrographs are reduced to event flow (minus `base`, e.g. the pre-storm
    recession; clipped at 0) and normalised to unit volume. Then:

        TE                timing efficiency: NSE of the unit-volume hydrographs.
                          1 = identical timing; 0 = no better than a uniform
                          distribution over the window. Insensitive to volume error.
        EMD_h             timing error (h): earth mover's distance between the
                          unit-volume hydrographs, sum |F_obs - F_sim| dt, with F
                          the cumulative fractions.
        centroid_shift_h  centre of mass of simulated minus observed runoff
                          (+ = model late). |centroid shift| <= EMD_h.
        peak_shift_h      simulated minus observed peak time (+ = model late).
        xcorr_lag_h       lag (within ±max_shift_h) of maximum cross-correlation
                          (+ = model late)
        xcorr_r           correlation at that lag

    tail_frac: both series are truncated where the observed event flow, after its
    peak, first falls below tail_frac × peak (default 10 %), which excludes the
    low-flow tail. None = whole window."""
    o, s_ = np.asarray(obs, float), np.asarray(sim, float)
    if base is not None:
        b = np.asarray(base, float)
        o, s_ = o - b, s_ - b
    o, s_ = np.clip(o, 0, None), np.clip(s_, 0, None)
    if tail_frac and o.max() > 0:
        ip = int(np.argmax(o))
        below = np.flatnonzero(o[ip:] < tail_frac * o[ip])
        if len(below):
            o, s_ = o[:ip + below[0] + 1], s_[:ip + below[0] + 1]
    if o.sum() <= 0 or s_.sum() <= 0:
        return {k: np.nan for k in ["TE", "EMD_h", "centroid_shift_h", "peak_shift_h",
                                    "xcorr_lag_h", "xcorr_r"]}
    fo, fs = o / o.sum(), s_ / s_.sum()
    te = 1 - np.sum((fo - fs) ** 2) / np.sum((fo - fo.mean()) ** 2)
    Fo, Fs = np.cumsum(fo), np.cumsum(fs)
    t = np.arange(len(o)) * dt
    best_r, best_k = -np.inf, 0
    kmax = int(max_shift_h / dt)
    for k in range(-kmax, kmax + 1):
        a_, b_ = (fo[k:], fs[:len(fs) - k]) if k >= 0 else (fo[:k], fs[-k:])
        if len(a_) > 3 and a_.std() > 0 and b_.std() > 0:
            r = np.corrcoef(a_, b_)[0, 1]
            if r > best_r:
                best_r, best_k = r, k
    return {"TE": float(te), "EMD_h": float(np.sum(np.abs(Fo - Fs)) * dt),
            "centroid_shift_h": float(np.sum(t * fs) - np.sum(t * fo)),
            "peak_shift_h": (int(np.argmax(fs)) - int(np.argmax(fo))) * dt,
            "xcorr_lag_h": -best_k * dt, "xcorr_r": float(best_r)}


def spike_lags(rain, q_obs, q_sim=None, dt: float = 0.25, max_lag_h: float = 36.0,
               min_frac: float = 0.2):
    """Rain spikes (in a basin-mean rain series) and the lag to the flow peak each
    produced. A spike is a rain peak of at least min_frac of the storm's maximum,
    3 h or more from the next. Each flow peak is assigned to the latest spike
    before it (within max_lag_h). Returns a list of
    (spike index, observed peak index or None, simulated peak index or None)."""
    rain = np.asarray(rain, float)
    if rain.max() <= 0:
        return []
    rpk, _ = signal.find_peaks(np.r_[0.0, rain, 0.0], prominence=min_frac * rain.max(),
                               distance=max(1, int(3 / dt)))
    rpk = rpk - 1

    def assign(q):
        if q is None:
            return {}
        q = np.asarray(q, float)
        pk, _ = signal.find_peaks(np.r_[q, 0.0], prominence=0.05 * np.ptp(q))
        out = {}
        for pk_ in pk:
            prior = rpk[(rpk <= pk_) & ((pk_ - rpk) * dt <= max_lag_h)]
            if len(prior) and prior[-1] not in out:
                out[prior[-1]] = pk_
        return out
    po, ps = assign(q_obs), assign(q_sim)
    return [(int(j), po.get(j), ps.get(j)) for j in rpk]


def baseflow_check(events: Sequence[DistEvent], kb_days: float, dt: float = 0.25) -> pd.DataFrame:
    """Detects storm windows that start on the falling limb of an earlier event.
    For each window: Q0, and the fraction of time steps in which observed flow is
    more than 10 % below the pre-storm recession Q0 exp(-t/k_b). A large fraction
    means the modelled baseflow is too high and Ia is overestimated."""
    rows = []
    for ev in events:
        q0 = ev.q0(kb_days)
        rec = recession(q0, len(ev.Q_obs), dt, kb_days)
        rows.append({"start": ev.time[0], "Q0_cfs": q0, "min_obs_cfs": float(np.min(ev.Q_obs)),
                     "share_below_recession": float(np.mean(ev.Q_obs < 0.9 * rec)),
                     "end_obs_over_recession": float(ev.Q_obs[-1] / rec[-1])})
    return pd.DataFrame(rows)


def starts_needed(start_log: pd.DataFrame, rel_tol: float = 0.01, confidence: float = 0.95) -> dict:
    """From a multi-start log (DistFit.starts): the share p of starts that reached
    the best sum of squares (within rel_tol), and the number of starts n needed so
    that at least one reaches it with the given confidence: 1 - (1 - p)^n >= conf."""
    sse = start_log.SSE.values
    p = float(np.mean(sse <= sse.min() * (1 + rel_tol)))
    n = int(np.ceil(np.log(1 - confidence) / np.log(1 - p))) if p < 1 else 1
    return {"starts_run": len(sse), "share_reaching_best": p, "starts_needed": n}


